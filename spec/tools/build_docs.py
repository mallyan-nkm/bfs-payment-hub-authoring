#!/usr/bin/env python3
"""Check the backlog and render the generated documents.

Reads   build/backlog/*.yaml, factory/inventory.yaml, conformance/kit.yaml, design/*.md
Writes  build/00-backlog.md, build/Cnn-*.md, and the generated blocks between
        <!-- NAME --> and <!-- /NAME --> markers in design/*.md and README.md

The backlog is data. Everything a story cites (an artefact, a test, a kit scenario, a
studio function, a check, a design part, a schema, another story) must exist, or this
tool exits 1. Run it after any change to the backlog or the factory pack:

    python3 tools/build_factory.py && python3 tools/validate.py && python3 tools/build_docs.py
"""
import pathlib
import re
import sys

import yaml

ROOT = pathlib.Path(__file__).resolve().parent.parent
BUILD = ROOT / "build"
DESIGN = ROOT / "design"
GEN = "<!-- Generated by tools/build_docs.py from build/backlog/. Edit the backlog, not this file. -->"

PHASES = {
    1: ("Spec", "G1", "This set, reviewed and accepted"),
    2: ("Walking skeleton", "G2", "One thin slice of every artefact kind runs in the studio and on Temporal"),
    3: ("Catalogue, AI and hooks", "G3", "The factory pack is complete and tested; AI authoring works in both languages; one hook of each type runs in a test tenant"),
    4: ("Portability", "G4", "The conformance kit is green on Temporal, DTFx and Flowable"),
    5: ("Governance", "G5", "Maker-checker, packs, configuration sets, the compatibility run, retirement and supersession"),
}
DECISIONS = {
    "D7": "Whether a script-behind may ever be a production runtime",
    "D8": "Artefacts as files in a repository per tenant",
    "D9": "A synchronous segment for instant rails",
    "D10": "Access to the current scheme rulebooks",
    "D13": "NRules on .NET as the rule evaluator",
    "D14": "Where scripts run",
    "D15": "Supersession policy: explicit only, even for a patch",
    "D16": "The default lookup date for values",
    "D17": "Where handlers run",
}
TOUCHES = {"C01": ["D8"], "C06": ["D13", "D16"], "C07": ["D14", "D7"], "C08": ["D14", "D7"], "C09": ["D17"], "C17": ["D8"],
           "C19": ["D15"], "C20": ["D9", "D17"], "C25": ["D10"], "C26": ["D10", "D9"]}
SIZES = (1, 3, 5, 8)

errors = []


def err(msg):
    errors.append(msg)


def slug(text):
    return re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")


# ------------------------------------------------------------------ load
groups = [yaml.safe_load(f.read_text()) for f in sorted((BUILD / "backlog").glob("*.yaml"))]
components = [dict(c, group=g["group"]) for g in groups for c in g["components"]]
comp_by_id = {c["id"]: c for c in components}
stories = {}
for c in components:
    for s in c["stories"]:
        if s["id"] in stories:
            err("story id %s is used twice" % s["id"])
        s["component"] = c["id"]
        s.setdefault("phase", c["phase"])
        s.setdefault("needs", [])
        stories[s["id"]] = s

inventory = yaml.safe_load((ROOT / "factory" / "inventory.yaml").read_text())
kit = yaml.safe_load((ROOT / "conformance" / "kit.yaml").read_text())
artefacts = {a["name"] for p in inventory["packs"] for a in p["artefacts"]}
tests = {a["name"] for p in inventory["packs"] for a in p["artefacts"] if a["kind"] == "test"}
scenarios = [s["id"] for s in kit["scenarios"]]
design_text = {f.name: f.read_text() for f in sorted(DESIGN.glob("*.md"))}
functions = set(re.findall(r"^\| (F-\d\d) \|", design_text["10-studio-functions.md"], re.M))
checks = set(re.findall(r"^\| (L\d\d) \|", design_text["05-workflow-dsl.md"], re.M))


def design_file(ref):
    """'Part 5' or 'Annex C' to a file name."""
    kind, _, n = ref.partition(" ")
    pat = "%02d-*.md" % int(n) if kind == "Part" else "annex-%s-*.md" % n.lower()
    hit = sorted(DESIGN.glob(pat))
    if not hit:
        err("design reference %r has no file" % ref)
        return None
    return hit[0].name


def schema_files(names):
    out = []
    for n in names:
        if n == "all":
            return ["every schema under `schemas/`"]
        if not (ROOT / "schemas" / (n + ".schema.json")).exists():
            err("schema %r does not exist" % n)
        out.append("`schemas/%s.schema.json`" % n)
    return out


# ---------------------------------------------------------------- checks
for c in components:
    if not re.fullmatch(r"C\d\d", c["id"]):
        err("%s is not a component id" % c["id"])
    for d in c["dependsOn"]:
        if d not in comp_by_id:
            err("%s depends on %s, which does not exist" % (c["id"], d))
    for ref in c["design"]:
        design_file(ref)
    schema_files(c["schemas"])
    for i, s in enumerate(c["stories"], 1):
        sid = s["id"]
        if sid != "%s-S%d" % (c["id"], i):
            err("%s should be %s-S%d" % (sid, c["id"], i))
        if s["sp"] not in SIZES:
            err("%s is sized %s; sizes are %s" % (sid, s["sp"], SIZES))
        if not (s["story"].startswith("As a") and ", I want " in s["story"] and ", so that " in s["story"]):
            err("%s is not written as a user story" % sid)
        if not s.get("dod") or not s.get("dos"):
            err("%s lacks a Definition of Done or a Definition of Success" % sid)
        for n in s["needs"]:
            if n not in stories:
                err("%s needs %s, which does not exist" % (sid, n))
                continue
            if stories[n]["phase"] > s["phase"]:
                err("%s is in phase %d but needs %s in phase %d" % (sid, s["phase"], n, stories[n]["phase"]))
            other = stories[n]["component"]
            if other != c["id"] and other not in c["dependsOn"]:
                err("%s needs %s, so %s must declare a dependency on %s" % (sid, n, c["id"], other))
        text = " ".join([s["title"], s["story"], s["dos"]] + s["dod"])
        for name in re.findall(r"\b(?:p|b|uae\.p|uae\.wps|uae\.aani)\.[a-z]+\.[a-z0-9-]+\.v\d+\b", text):
            if name not in artefacts:
                err("%s cites %s, which is not in the factory pack" % (sid, name))
        for t in re.findall(r"\b(?:AANI|WPS|P|BANK)-[A-Z]+-\d{3}\b", text):
            if t not in tests:
                err("%s cites test %s, which does not exist" % (sid, t))
        for k in re.findall(r"\bCK-[A-Z]+-\d\d\b", text):
            if k not in scenarios:
                err("%s cites kit scenario %s, which does not exist" % (sid, k))
        for f in re.findall(r"\bF-\d\d\b", text):
            if f not in functions:
                err("%s cites studio function %s, which does not exist" % (sid, f))
        for l in re.findall(r"\bL\d\d\b", text):
            if l not in checks:
                err("%s cites check %s, which is not in the catalogue of Part 5" % (sid, l))
        for r in re.findall(r"\bC\d\d-S\d+\b", text):
            if r not in stories:
                err("%s cites story %s, which does not exist" % (sid, r))


def expand(ids):
    """'CK-HOOK-01 to 04' style ranges are written out in the backlog text; read them here."""
    out = set()
    for m in re.finditer(r"\b(CK-[A-Z]+)-(\d\d)(?:(?: to | and )(\d\d))?", ids):
        lo, hi = int(m.group(2)), int(m.group(3) or m.group(2))
        if " to " in m.group(0):
            out.update("%s-%02d" % (m.group(1), i) for i in range(lo, hi + 1))
        else:
            out.update(["%s-%02d" % (m.group(1), lo), "%s-%02d" % (m.group(1), hi)])
    return out


covered = set()
for s in comp_by_id["C09"]["stories"]:
    covered |= expand(s["dos"])
for k in scenarios:
    if k not in covered:
        err("kit scenario %s is not the success line of any interpreter story in C09" % k)
for k in sorted(covered):
    if k not in scenarios:
        err("C09 cites kit scenario %s, which does not exist" % k)


def cyclic(graph):
    state = {}

    def visit(n, path):
        if state.get(n) == 2:
            return None
        if state.get(n) == 1:
            return path + [n]
        state[n] = 1
        for m in graph.get(n, []):
            hit = visit(m, path + [n])
            if hit:
                return hit
        state[n] = 2
        return None

    for n in graph:
        hit = visit(n, [])
        if hit:
            return hit
    return None


loop = cyclic({c["id"]: c["dependsOn"] for c in components})
if loop:
    err("components depend on each other in a loop: %s" % " > ".join(loop))
loop = cyclic({sid: s["needs"] for sid, s in stories.items()})
if loop:
    err("stories need each other in a loop: %s" % " > ".join(loop))

# requirement ids are unique across the design
seen = {}
for name, text in design_text.items():
    for rid in re.findall(r"^\| (R-\d\d-\d\d) \|", text, re.M):
        if rid in seen:
            err("requirement %s appears in %s and in %s" % (rid, seen[rid], name))
        seen[rid] = name

if errors:
    for e in errors:
        print("ERROR " + e)
    print("%d error(s); nothing was written" % len(errors))
    sys.exit(1)


# ---------------------------------------------------------------- render
def order(ids):
    """Stories in an order that respects needs, then phase, then id."""
    done, out = set(), []
    pending = sorted(ids, key=lambda i: (stories[i]["phase"], i[:3], int(i.split("-S")[1])))
    while pending:
        for i in pending:
            if all(n in done or n not in ids for n in stories[i]["needs"]):
                out.append(i)
                done.add(i)
                pending.remove(i)
                break
    return out


def story_block(c, s):
    files = ["`design/%s`" % design_file(r) for r in c["design"]]
    lines = ["### %s %s" % (s["id"], s["title"]), "",
             "Size: %d SP. Phase %d. Branch: `story/%s-%s`." % (s["sp"], s["phase"], s["id"].lower(), slug(s["title"])), "",
             "**Story.** %s" % s["story"], "",
             "**Definition of Ready**", "",
             "- Read: %s; %s." % (", ".join(files), ", ".join(schema_files(c["schemas"]))),
             "- Done first: %s." % (", ".join("`%s`" % n for n in s["needs"]) if s["needs"] else "nothing in this backlog"),
             "- Fixtures: `factory/`, `examples/`" + (" and `conformance/kit.yaml`." if "CK-" in s["dos"] or c["id"] == "C23" else "."), "",
             "**Definition of Done**", ""]
    lines += ["- %s" % d for d in s["dod"]]
    lines += ["- The common Definition of Done in `CLAUDE.md` holds.", "",
              "**Definition of Success**", "", "- %s" % s["dos"], ""]
    return lines


def component_doc(c):
    sp = sum(s["sp"] for s in c["stories"])
    phases = sorted({s["phase"] for s in c["stories"]})
    out = [GEN, "", "# %s %s" % (c["id"], c["title"]), "",
           "Group: %s. Phase: %s. Stories: %d. Size: %d SP." % (c["group"], ", ".join(str(p) for p in phases), len(c["stories"]), sp), "",
           "## Purpose", "", c["purpose"], "",
           "## Read first", ""]
    out += ["- `design/%s`" % design_file(r) for r in c["design"]]
    out += ["- %s" % f for f in schema_files(c["schemas"])]
    out += ["- `CLAUDE.md`, for the guard-rails and the common Definition of Done", "",
            "## Depends on", ""]
    out += ["- %s %s" % (d, comp_by_id[d]["title"]) for d in c["dependsOn"]] or ["- Nothing in this backlog."]
    if c["id"] in TOUCHES:
        out += ["", "## Open decisions that touch this component", ""]
        out += ["- %s: %s." % (d, DECISIONS[d]) for d in TOUCHES[c["id"]]]
        out += ["", "A story MAY start before its decision closes if it isolates the choice behind an interface and says so in its plan."]
    out += ["", "## Success for the component", "", c["dos"], "", "## Stories", ""]
    for s in c["stories"]:
        out += story_block(c, s)
    return "\n".join(out).rstrip() + "\n"


for old in BUILD.glob("C[0-9][0-9]-*.md"):
    old.unlink()
for c in components:
    (BUILD / ("%s-%s.md" % (c["id"], slug(c["title"])))).write_text(component_doc(c))

total_sp = sum(s["sp"] for s in stories.values())
b = [GEN, "", "# Build backlog", "",
     "Status: draft 0.1. %d components, %d stories, %d story points. Phase 1 is this specification; the backlog starts at phase 2." % (len(components), len(stories), total_sp), "",
     "## How to use it", "",
     "One file per component, `Cnn-<name>.md`. Each holds the component's purpose, what to read first, and its stories. "
     "A story is a prompt: give it to Claude Code as written, with `CLAUDE.md` in the repository root.", "",
     "1. Take the next story whose `Done first` list is complete.",
     "2. Start in plan mode. The plan names the files to add or change and the tests to write first. Review the plan before any code.",
     "3. Work on the story's branch. One story, one branch, one pull request.",
     "4. The story is done when every Definition of Done line holds. It has succeeded when the Definition of Success line is shown, with evidence, in the pull request.", "",
     "Sizes are 1, 3, 5 or 8 story points. An 8 is the ceiling: a story that grows past it is split before work continues. "
     "Sizes are estimates made from the spec and SHOULD be revised when a component's first story is done.", "",
     "The backlog names no stack beyond what the design fixes: scripts-behind in TypeScript and Python (Part 8), rule semantics after NRules (Part 4), "
     "and the three engines (Part 9). Choose the studio's own stack in a short decision record before C01 starts.", "",
     "## Phases", "",
     "| Phase | Name | Gate | What the gate shows | Stories | Points |", "| --- | --- | --- | --- | --- | --- |"]
for ph, (name, gate, shows) in PHASES.items():
    ss = [s for s in stories.values() if s["phase"] == ph]
    b.append("| %d | %s | %s | %s | %s | %s |" % (ph, name, gate, shows, len(ss) if ph > 1 else "", sum(s["sp"] for s in ss) if ph > 1 else ""))
b += ["", "## Components", "",
      "| Id | Component | Group | Phases | Stories | Points | Depends on |", "| --- | --- | --- | --- | --- | --- | --- |"]
for c in components:
    phases = sorted({s["phase"] for s in c["stories"]})
    b.append("| [%s](%s-%s.md) | %s | %s | %s | %d | %d | %s |" % (
        c["id"], c["id"], slug(c["title"]), c["title"], c["group"], ", ".join(str(p) for p in phases), len(c["stories"]),
        sum(s["sp"] for s in c["stories"]), ", ".join(c["dependsOn"]) or "none"))
b += ["", "## Open decisions and the components they touch", "",
      "| Decision | Subject | Components |", "| --- | --- | --- |"]
for d, subject in DECISIONS.items():
    b.append("| %s | %s | %s |" % (d, subject, ", ".join(sorted(c for c, ds in TOUCHES.items() if d in ds))))
b += ["", "## Stories in build order", "",
      "Within a phase the order respects every `Done first` line. Stories with no line between them MAY run in parallel.", ""]
for ph in sorted(PHASES):
    ids = [i for i, s in stories.items() if s["phase"] == ph]
    if not ids:
        continue
    b += ["### Phase %d, %s" % (ph, PHASES[ph][0].lower()), "",
          "| Story | Title | Points | Done first |", "| --- | --- | --- | --- |"]
    for i in order(ids):
        s = stories[i]
        b.append("| %s | %s | %d | %s |" % (i, s["title"], s["sp"], ", ".join(s["needs"]) or ""))
    b.append("")
(BUILD / "00-backlog.md").write_text("\n".join(b).rstrip() + "\n")

# ------------------------------------------------------- inventory blocks
KINDS = ["activity", "rule", "ruleset", "table", "port", "simulator", "workflow", "scheme", "extension", "hook", "test"]


def inv_summary():
    rows = ["| Pack | Type | " + " | ".join(k.capitalize() for k in KINDS) + " | Total |", "| --- | --- |" + " --- |" * (len(KINDS) + 1)]
    tot = dict.fromkeys(KINDS, 0)
    for p in inventory["packs"]:
        where = "`factory/%s/`" % p["scope"] if p["packType"] == "shared" else "`examples/bank/`"
        rows.append("| %s | %s | " % (where, p["packType"]) + " | ".join(str(p["counts"].get(k, "")) for k in KINDS) + " | %d |" % p["total"])
        for k in KINDS:
            tot[k] += p["counts"].get(k, 0)
    rows.append("| Total | | " + " | ".join(str(tot[k]) for k in KINDS) + " | %d |" % sum(p["total"] for p in inventory["packs"]))
    return rows


def inv_scope(scope):
    p = next(x for x in inventory["packs"] if x["scope"] == scope)
    rows = ["| Kind | Count | Artefacts |", "| --- | --- | --- |"]
    for k in KINDS:
        names = [a["name"] for a in p["artefacts"] if a["kind"] == k]
        if names:
            rows.append("| %s | %d | %s |" % (k.capitalize(), len(names), ", ".join("`%s`" % n for n in names)))
    rows.append("| Total | %d | |" % p["total"])
    return rows


def counts_block():
    val = (ROOT / "tools" / "validate.py").read_text()
    in_validator = sorted(set(re.findall(r'(?:err|warn)\("(L\d\d)"', val)))
    mutations = len(re.findall(r'^    \("M\d\d"', (ROOT / "tools" / "mutation_tests.py").read_text(), re.M))
    shared = sum(p["total"] for p in inventory["packs"] if p["packType"] == "shared")
    parts = len(list(DESIGN.glob("[0-9][0-9]-*.md")))
    annexes = len(list(DESIGN.glob("annex-*.md")))
    reqs = sum(len(re.findall(r"^\| R-\d\d-\d\d \|", t, re.M)) for t in design_text.values())
    return ["| What | Count |", "| --- | --- |",
            "| Design parts and annexes | %d and %d |" % (parts, annexes),
            "| Numbered requirements | %d |" % reqs,
            "| Schemas | %d |" % len(list((ROOT / "schemas").glob("*.schema.json"))),
            "| Factory artefacts in `p`, `uae.p`, `uae.wps`, `uae.aani` | %d |" % shared,
            "| Example bank artefacts | %d |" % sum(p["total"] for p in inventory["packs"] if p["packType"] == "bank"),
            "| Composite activities, each with a subflow | %d |" % len(list((ROOT / "factory").rglob("*.sub.*.yaml"))),
            "| Test cases in the packs | %d |" % len(tests),
            "| Conformance scenarios | %d |" % len(scenarios),
            "| Checks in `tools/validate.py` | %d (%s to %s) |" % (len(in_validator), in_validator[0], in_validator[-1]),
            "| Mutation cases that prove them | %d |" % mutations,
            "| Build components, stories, story points | %d, %d, %d |" % (len(components), len(stories), total_sp)]


BLOCKS = {"INVENTORY:summary": inv_summary, "COUNTS": counts_block}
for p in inventory["packs"]:
    BLOCKS["INVENTORY:%s" % p["scope"]] = (lambda s=p["scope"]: inv_scope(s))

filled = 0
for f in sorted(DESIGN.glob("*.md")) + [ROOT / "README.md", ROOT / "factory" / "README.md"]:
    if not f.exists():
        continue
    text = f.read_text()
    for name, fn in BLOCKS.items():
        pat = re.compile(r"<!-- %s -->(?:.*?<!-- /%s -->)?" % (re.escape(name), re.escape(name)), re.S)
        if pat.search(text):
            block = "<!-- %s -->\n%s\n<!-- /%s -->" % (name, "\n".join(fn()), name)
            text = pat.sub(lambda m: block, text)
            filled += 1
    f.write_text(text)

# a last check on everything written by hand or by tool: no em-dash anywhere
dashes = []
for f in ROOT.rglob("*"):
    if f.is_file() and f.suffix in (".md", ".yaml", ".json", ".py", ".txt") and "__pycache__" not in f.parts:
        if chr(0x2014) in f.read_text():
            dashes.append(str(f.relative_to(ROOT)))
if dashes:
    print("ERROR em-dash found in: %s" % ", ".join(dashes))
    sys.exit(1)

print("components %d  stories %d  points %d  generated blocks %d" % (len(components), len(stories), total_sp, filled))
for ph in sorted(PHASES):
    ss = [s for s in stories.values() if s["phase"] == ph]
    if ss:
        print("  phase %d  %-24s %3d stories  %3d points" % (ph, PHASES[ph][0], len(ss), sum(s["sp"] for s in ss)))
