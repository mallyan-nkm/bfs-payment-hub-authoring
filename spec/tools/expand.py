#!/usr/bin/env python3
"""Expand authored workflows into the form an engine runs.

A designer's workflow calls a composite activity as one step. This tool replaces each
such step with a block that holds the steps of the composite's subflow, so that what
is left uses only the portable core. It is the reference for build story C04-S6; it
is not the product.

    python3 tools/expand.py            write expanded/<workflow>.yaml for every workflow that calls a composite
    python3 tools/expand.py --check    fail if any stored expansion differs from a fresh one

What expansion does, in order, for each step that calls a composite activity:
  1. takes the subflow named by the activity's implementation, expanded in its turn;
  2. prefixes every inner step id, and every outcomeOf that names one, with the calling step's id and a dot;
  3. gives an await that has no timeout the calling step's reply time: the step's policy, else the activity's;
  4. wraps the result in a block that carries the calling step's id and its handle.
Segments are inlined by the same pass in the product (C09-S1); this tool leaves a use step as it is.
"""
import copy
import hashlib
import json
import pathlib
import sys

import yaml
from jsonschema import Draft202012Validator
from referencing import Registry, Resource

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "expanded"
HEADER = "# Generated by tools/expand.py from the authored workflow. Never edit; never store as authored.\n"

docs = {}
for base in ("factory", "examples"):
    for f in sorted((ROOT / base).rglob("*.yaml")):
        for d in yaml.safe_load_all(f.read_text()):
            if isinstance(d, dict) and d.get("name"):
                docs[d["name"]] = d

schemas = {}
for f in sorted((ROOT / "schemas").glob("*.schema.json")):
    s = json.loads(f.read_text())
    schemas[s["$id"]] = s
registry = Registry().with_resources([(i, Resource.from_contents(s)) for i, s in schemas.items()])
workflow_schema = Draft202012Validator(schemas["urn:th:schema:workflow"], registry=registry)


class Dumper(yaml.SafeDumper):
    def increase_indent(self, flow=False, indentless=False):
        return super().increase_indent(flow, False)


def canon_hash(doc):
    return "sha256:" + hashlib.sha256(json.dumps(doc, sort_keys=True, separators=(",", ":"), ensure_ascii=False).encode()).hexdigest()


def composite(name):
    a = docs.get(name) or {}
    return a.get("kind") == "activity" and (a.get("implementation") or {}).get("binding") == "subflow"


def nested(st):
    """Every (holder, key) in a step whose value is a step list."""
    for key, action in (st.get("handle") or {}).items():
        if isinstance(action, list):
            yield st["handle"], key
    if "switch" in st:
        for key in st["switch"]["cases"]:
            yield st["switch"]["cases"], key
        if "default" in st["switch"]:
            yield st["switch"], "default"
    if "parallel" in st:
        for i in range(len(st["parallel"]["branches"])):
            yield st["parallel"]["branches"], i
    for key in ("forEach", "loop", "block"):
        if key in st:
            yield st[key], "do"
    if "await" in st and isinstance(st["await"]["onTimeout"], list):
        yield st["await"], "onTimeout"
    if "try" in st:
        yield st, "try"
        for c in st.get("catch", []):
            if isinstance(c["do"], list):
                yield c, "do"


def walk(steps):
    for st in steps:
        yield st
        for holder, key in nested(st):
            yield from walk(holder[key])


def qualify(holder, key, act):
    """A duration that names a parameter of the composite: name it in full and carry its default (R-05-45)."""
    v = holder.get(key)
    if isinstance(v, dict) and "parameter" in v and "#" not in v["parameter"]:
        decl = (act.get("parameters") or {}).get(v["parameter"])
        if decl is None:
            sys.exit("%s declares no parameter %s" % (act["name"], v["parameter"]))
        holder[key] = {"parameter": "%s#%s" % (act["name"], v["parameter"]), "default": decl["default"]}


def rename(steps, prefix, policy, act):
    """Prefix the ids inside a subflow and resolve its reply waits against the calling step."""
    inner = {st["id"] for st in walk(steps) if "id" in st}
    for st in walk(steps):
        if "id" in st:
            st["id"] = "%s.%s" % (prefix, st["id"])
        for key in ("loop", "switch"):
            ref = (st.get(key) or {}).get("until" if key == "loop" else "by") or {}
            if ref.get("outcomeOf") in inner:
                ref["outcomeOf"] = "%s.%s" % (prefix, ref["outcomeOf"])
        if "wait" in st:
            qualify(st, "wait", act)
        if "await" in st and "timeout" in st["await"]:
            qualify(st["await"], "timeout", act)
        if "await" in st and "timeout" not in st["await"]:
            if "replyTimeout" not in policy:
                sys.exit("%s: an await has no timeout and the calling step has no replyTimeout" % prefix)
            st["await"] = {**st["await"], "timeout": policy["replyTimeout"]}
            if "replyCalendar" in policy and "calendar" not in st["await"]:
                st["await"]["calendar"] = policy["replyCalendar"]
            # R-05-47: a wait the bank may set names the composite's parameter; the policy's value is its default
            if "replyTimeoutParameter" in policy:
                st["await"]["timeoutParameter"] = "%s#%s" % (act["name"], policy["replyTimeoutParameter"])
            if "replyCalendarParameter" in policy and "calendar" in st["await"]:
                st["await"]["calendarParameter"] = "%s#%s" % (act["name"], policy["replyCalendarParameter"])
            # keep the key order of a hand-written await: message, correlateBy, timeout, calendar, onTimeout
            order = ["message", "correlateBy", "family", "timeout", "timeoutParameter", "calendar", "calendarParameter", "onTimeout"]
            st["await"] = {k: st["await"][k] for k in order if k in st["await"]}
    return steps


def expand(steps, stack=()):
    out = []
    for st in steps:
        st = copy.deepcopy(st)
        for holder, key in list(nested(st)):
            holder[key] = expand(holder[key], stack)
        if "call" in st and composite(st["call"]):
            act = docs[st["call"]]
            sub = docs[act["implementation"]["subflow"]]
            if act["name"] in stack:
                sys.exit("composite %s calls itself through its subflow" % act["name"])
            if "id" not in st:
                sys.exit("a step that calls the composite %s needs an id" % act["name"])
            policy = {**(act.get("policy") or {}), **(st.get("policy") or {})}
            # a step that fixes the wait itself overrides the bank's parameter
            for fixed, param in (("replyTimeout", "replyTimeoutParameter"), ("replyCalendar", "replyCalendarParameter")):
                if fixed in (st.get("policy") or {}):
                    policy.pop(param, None)
            body = rename(expand(copy.deepcopy(sub["do"]), stack + (act["name"],)), st["id"], policy, act)
            block = {"id": st["id"], "block": {"of": act["name"], "by": sub["name"], "do": body}}
            if st.get("handle"):
                block["handle"] = st["handle"]
            out.append(block)
        else:
            out.append(st)
    return out


def check(doc):
    """What must hold of every expanded workflow."""
    problems = ["schema: %s at /%s" % (e.message[:120], "/".join(str(x) for x in e.path)) for e in workflow_schema.iter_errors(doc)]
    steps = list(walk(doc["do"])) + list(walk(doc.get("finally") or [])) + list(walk((doc.get("deadline") or {}).get("do") or []))
    ids = [st["id"] for st in steps if "id" in st]
    problems += ["step id %s is used twice" % i for i in sorted({i for i in ids if ids.count(i) > 1})]
    for st in steps:
        if "call" in st and composite(st["call"]):
            problems.append("step %s still calls the composite %s" % (st.get("id"), st["call"]))
        if "await" in st and "timeout" not in st["await"]:
            problems.append("await %s has no timeout" % st.get("id"))
        if "block" in st:
            outs = {o["name"] for o in docs[st["block"]["of"]]["outcomes"]}
            inside = list(walk(st["block"]["do"]))
            given = {s["return"] for s in inside if "return" in s}
            for s in inside:
                for a in list((s.get("handle") or {}).values()) + [(s.get("await") or {}).get("onTimeout")]:
                    if isinstance(a, dict) and "return" in a:
                        given.add(a["return"])
            problems += ["block %s returns %r, which %s does not declare" % (st["id"], o, st["block"]["of"]) for o in sorted(given - outs)]
    return problems


def main():
    want = {}
    for name, d in sorted(docs.items()):
        if d.get("kind") != "workflow" or d["wfKind"] == "subflow":
            continue
        parts = {k: expand(v) for k, v in (("do", d["do"]), ("finally", d.get("finally"))) if v}
        if d.get("deadline"):
            parts["deadline"] = {**d["deadline"], "do": expand(d["deadline"]["do"])}
        if not any("block" in st for part in ("do", "finally") for st in walk(parts.get(part) or [])):
            continue
        doc = {**d, **parts, "form": "expanded", "expandedFrom": {"release": d["release"], "hash": canon_hash(d)}}
        problems = check(doc)
        if problems:
            sys.exit("%s does not expand cleanly:\n  %s" % (name, "\n  ".join(problems)))
        want[name + ".yaml"] = HEADER + yaml.dump(doc, Dumper=Dumper, sort_keys=False, allow_unicode=True, width=110)
    have = {f.name: f.read_text() for f in OUT.glob("*.yaml")} if OUT.exists() else {}
    if "--check" in sys.argv:
        stale = sorted(n for n in set(want) | set(have) if want.get(n) != have.get(n))
        if stale:
            sys.exit("expanded/ is out of date: %s. Run python3 tools/expand.py" % ", ".join(stale))
        print("expanded/ is up to date: %d workflows" % len(want))
        return
    OUT.mkdir(exist_ok=True)
    for n in set(have) - set(want):
        (OUT / n).unlink()
    for n, text in want.items():
        (OUT / n).write_text(text)
        print("expanded", n)


if __name__ == "__main__":
    main()
