// The content branch as the studio's only store (R-11-21 to R-11-25; R-09-19 to R-09-22 as amended),
// against the fake GitHub: real SHA semantics, fast-forward checks, nothing on disk.

const ROOT = 'content-configurations';
const call = (env: any, method: string, p: string, body: any = {}, query: any = {}) => dispatch(env, { method, path: p, query, body });
const files = (env: any, branch = BRANCH) => fake().files(env.store.content.repository, branch);
const log = (env: any, branch = BRANCH) => fake().log(env.store.content.repository, branch);
const studioBranches = (env: any) => fake().branches(env.store.content.repository).filter((b) => b.startsWith('studio/'));

const ACT = (n: string, extra: any = {}) => ({
  kind: 'activity', name: `p.enrich.cs-note-${n}.v1`, release: '1.0.0', title: 'Note', type: 'enrich', reads: ['header'], writes: ['facts.note'],
  outcomes: [{ name: 'done', primary: true }], effect: 'pure', implementation: { binding: 'builtin', service: 'noop' },
  provenance: { origin: 'authored', status: 'provisional', clauses: ['Content store test'] }, ...extra,
});

async function draft(env: any, doc: any, actor = 'shared.designer') {
  const d = await call(env, 'POST', '/api/drafts', { tenant: 'owner', actor, doc });
  expect(d.status, JSON.stringify(d.body)).toBe(200);
  return d.body.draft.key as string;
}

async function publish(env: any, key: string, checker = 'shared.checker') {
  const p = await call(env, 'POST', '/api/publish', { tenant: 'owner', key, checker });
  expect(p.status, JSON.stringify(p.body).slice(0, 400)).toBe(200);
  return p.body;
}

