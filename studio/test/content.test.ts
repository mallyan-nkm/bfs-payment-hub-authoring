describe('a branch per change set (R-11-22)', () => {
  it('each draft save is a commit on studio/<id>; a related draft joins it; a restart finds both', async () => {
    const env = freshEnv();
    const head = log(env)[0].sha;
    const key = await draft(env, ACT('a'));
    const id = env.store.entries.get(key)!.changeSet!;
    expect(id).toMatch(/^CS-\d{4}-\d\d-\d\d-\d{3}$/);
    expect(studioBranches(env)).toEqual([`studio/${id}`]);
    expect(log(env)[0].sha).toBe(head); // the content branch is not written by a draft
    await draft(env, ACT('a', { title: 'Note, saved again' }));
    const test = { kind: 'test', id: 'CS-NOTE-001', target: 'p.enrich.cs-note-a.v1', level: 'activity', evaluationDate: '2026-11-21', given: { context: { header: {} } }, expect: { outcome: 'done' } };
    const tkey = await draft(env, test);
    expect(env.store.entries.get(tkey)!.changeSet).toBe(id);
    const commits = log(env, `studio/${id}`);
    expect(commits.length).toBe(log(env).length + 3);
    expect(commits[0].message).toMatch(new RegExp(`^Draft CS-NOTE-001 \\(${id}\\)`));
    expect(commits.every((c) => c.author === 'TransactHub Studio' || c.sha === head || log(env).some((x) => x.sha === c.sha))).toBe(true);
    const branchFiles = files(env, `studio/${id}`);
    expect(branchFiles[`${ROOT}/artefacts/p/p.enrich.cs-note-a.v1/1.0.0.yaml`]).toMatch(/title: Note, saved again/);
    expect(branchFiles[`${ROOT}/audit/change-sets/${id}.yaml`]).toMatch(/action: save-draft/);

    const again = await restart(env);
    expect(again.store.drafts('owner').map((d) => [d.key, d.changeSet, d.status])).toEqual(expect.arrayContaining([[key, id, 'draft'], [tkey, id, 'draft']]));
    expect(again.store.entries.get(key)!.doc.title).toBe('Note, saved again');
    expect(again.store.audit.filter((a) => a.changeSet === id).map((a) => a.actor)).toEqual(['shared.designer', 'shared.designer', 'shared.designer']);
  });

  it('approval publishes the change set into the content branch as one commit, which takes its branch in', async () => {
    const env = freshEnv();
    const key = await draft(env, ACT('b'));
    const id = env.store.entries.get(key)!.changeSet!;
    await call(env, 'POST', '/api/review', { tenant: 'owner', actor: 'shared.designer', key });
    const before = log(env).length;
    const draftHead = log(env, `studio/${id}`)[0].sha;
    const pub = await publish(env, key);
    expect(pub.changeSet.id).toBe(id);
    expect(pub.git).toMatchObject({ status: 'committed', branch: BRANCH, changeSet: id });
    expect(pub.git.files.sort()).toEqual([`${ROOT}/artefacts/p/p.enrich.cs-note-b.v1/1.0.0.yaml`, `${ROOT}/audit/change-sets/${id}.yaml`, `${ROOT}/change-sets/${id}.yaml`]);
    const l = log(env);
    expect(l.length).toBe(before + 1);
    expect(l[0].parents).toEqual([l[1].sha, draftHead]);
    expect(l[0].message).toMatch(new RegExp(`^Release change set ${id}: 1 artefact[\\s\\S]*Maker: shared\\.designer\\nChecker: shared\\.checker`));
    expect(l[0].sha).toBe(pub.git.commit);
    expect(fake().forced).toBe(0);
    // The content branch took the change set branch in whole: the branch is deleted (R-11-26).
    expect(pub.git.deletedBranches).toEqual([`studio/${id}`]);
    expect(studioBranches(env)).toEqual([]);
    expect(fake().deleted).toContain(`${env.store.content!.repository} studio/${id}`);

    const again = await restart(env);
    expect(again.store.get('p.enrich.cs-note-b.v1', '1.0.0')).toMatchObject({ status: 'published', source: 'studio', maker: 'shared.designer', checker: 'shared.checker' });
    expect(again.store.drafts('owner')).toEqual([]);
    expect((again.store.extra.changeSets ?? []).map((c: any) => c.id)).toContain(id);
  });

  it('in pull-request mode, approval opens a pull request from the change set branch and leaves the content branch alone', async () => {
    const env = freshEnv();
    expect((await call(env, 'PUT', '/api/git', { actor: 'shared.designer', mode: 'pull-request' })).status).toBe(403);
    const s = await call(env, 'PUT', '/api/git', { actor: 'shared.checker', mode: 'pull-request' });
    expect(s.status, JSON.stringify(s.body)).toBe(200);
    expect(files(env)[`${ROOT}/governance/settings.yaml`]).toMatch(/mode: pull-request/);
    const key = await draft(env, ACT('c'));
    const id = env.store.entries.get(key)!.changeSet!;
    const head = log(env)[0].sha;
    const pub = await publish(env, key);
    expect(pub.git).toMatchObject({ status: 'pull-request', branch: `studio/${id}`, pullRequest: { opened: true, branch: `studio/${id}` } });
    expect(log(env)[0].sha).toBe(head);
    expect(files(env, `studio/${id}`)[`${ROOT}/change-sets/${id}.yaml`]).toBeDefined();
    expect(env.store.entries.get(key)).toMatchObject({ status: 'in-review', awaitingMerge: `studio/${id}` });
    expect((await publish(env, key).catch(() => undefined)) ?? 'refused').toBe('refused');
    const pulls = fake().repo(env.store.content!.repository).pulls;
    expect(pulls).toHaveLength(1);
    expect(pulls[0]).toMatchObject({ head: `studio/${id}`, base: BRANCH, title: `Release change set ${id}` });

    // Waiting for the merge survives a restart; once merged, the change set is published.
    expect((await restart(env)).store.entries.get(key)).toMatchObject({ status: 'in-review', awaitingMerge: `studio/${id}` });
    fake().mergePull(env.store.content!.repository, pulls[0].number);
    // A command that only reads sees the merge and deletes nothing.
    const reader = envFor(await ContentStore.open({ ...env.store.content!.conn, readOnly: true }), { banks: [] });
    expect(reader.store.get('p.enrich.cs-note-c.v1', '1.0.0')?.status).toBe('published');
    expect(studioBranches(env)).toEqual([`studio/${id}`]);
    // The studio, reading the branch, finds the pull request merged and deletes its branch (R-11-26).
    const merged = await restart(env);
    expect(merged.store.get('p.enrich.cs-note-c.v1', '1.0.0')?.status).toBe('published');
    expect(merged.store.drafts('owner')).toEqual([]);
    expect(studioBranches(env)).toEqual([]);
    expect(merged.store.content!.deletedBranches).toEqual([`studio/${id}`]);
    expect(fake().branches(env.store.content!.repository)).toContain(BRANCH);
  }, 60000);
});

