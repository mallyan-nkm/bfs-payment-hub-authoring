// The content branch as the studio's only store (R-11-21 to R-11-25; R-09-19 to R-09-22 as amended),
// against the fake GitHub: real SHA semantics, fast-forward checks, nothing on disk.

const ROOT = 'content-configurations';
const call = (env: any, method: string, p: string, body: any = {}, query: any = {}) => dispatch(env, { method, path: p, query, body });
const files = (env: any, branch = BRANCH) => fake().files(env.store.content.repository, branch);
const log = (env: any, branch = BRANCH) => fake().log(env.store.content.repository, branch);
const studioBranches = (env: any) => fake().branches(env.store.content.repository).filter((b) => b.startsWith('studio/'));

const ACT = (n: string, extra: any = {}) => ({
  kind: 'activity', name: `p.enrich.cs-note-${n}.v1`, release: '1.0.0', title: 'Note', type: 'enrich', reads: ['header'], writes: ['facts.note'],
  outcomes: [{ name: 'done', primary: true }], effect: 'pure', implementation: { binding: 'builtin', service: 'noop' },
  provenance: { origin: 'authored', status: 'provisional', clauses: ['Content store test'] }, ...extra,
});

async function draft(env: any, doc: any, actor = 'shared.designer') {
  const d = await call(env, 'POST', '/api/drafts', { tenant: 'owner', actor, doc });
  expect(d.status, JSON.stringify(d.body)).toBe(200);
  return d.body.draft.key as string;
}

async function publish(env: any, key: string, checker = 'shared.checker') {
  const p = await call(env, 'POST', '/api/publish', { tenant: 'owner', key, checker });
  expect(p.status, JSON.stringify(p.body).slice(0, 400)).toBe(200);
  return p.body;
}

describe('the content branch is the only store (R-11-21)', () => {
  it('reads the factory and the example bank from the branch; each seeded document names its source in spec/', () => {
    const env = freshEnv();
    const wf = env.store.get('p.wf.commercial.v1')!;
    expect(wf).toMatchObject({ status: 'published', source: 'spec', path: 'factory/p/workflows/p.wf.commercial.v1.yaml' });
    expect(env.store.content!.files.get('artefacts/p/p.wf.commercial.v1/1.0.0.yaml')).toMatch(/^# Generated by `npm run studio -- seed-content` from spec\/factory\/p\/workflows\/p\.wf\.commercial\.v1\.yaml/);
    expect(env.store.configurationSet('example-bank')).toMatchObject({ tenant: 'example-bank' });
    expect(env.store.all().filter((e) => e.tenant === 'example-bank').length).toBeGreaterThan(10);
    // Only the conformance kit, the engines' fixture, is read from spec/.
    expect(env.store.all().filter((e) => e.path.startsWith('conformance/')).map((e) => e.kind)).toEqual(['conformance-kit']);
  });

  it('calls only the endpoints of its client', async () => {
    const env = freshEnv();
    const before = fake().requests.length;
    const key = await draft(env, ACT('endpoints'));
    await call(env, 'POST', '/api/review', { tenant: 'owner', actor: 'shared.designer', key });
    await publish(env, key);
    await restart(env);
    const used = fake().requests.slice(before).filter((r) => r.path.includes(env.store.content!.repository));
    const patterns = ENDPOINTS.map((e) => {
      const [method, p] = e.split(' ');
      return { method, re: new RegExp('^/repos/[^/]+/[^/]+' + p.replace(/[.]/g, '\\.').replace(/\{[^}]+\}/g, '.+') + '$') };
    });
    for (const r of used) expect(patterns.some((p) => p.method === r.method && p.re.test(r.path)), `${r.method} ${r.path}`).toBe(true);
    expect(new Set(used.map((r) => r.method))).toEqual(new Set(['GET', 'POST', 'PATCH']));
  });
});

describe('a branch per change set (R-11-22)', () => {
  it('each draft save is a commit on studio/<id>; a related draft joins it; a restart finds both', async () => {
    const env = freshEnv();
    const head = log(env)[0].sha;
    const key = await draft(env, ACT('a'));
    const id = env.store.entries.get(key)!.changeSet!;
    expect(id).toMatch(/^CS-\d{4}-\d\d-\d\d-\d{3}$/);
    expect(studioBranches(env)).toEqual([`studio/${id}`]);
    expect(log(env)[0].sha).toBe(head); // the content branch is not written by a draft
    await draft(env, ACT('a', { title: 'Note, saved again' }));
    const test = { kind: 'test', id: 'CS-NOTE-001', target: 'p.enrich.cs-note-a.v1', level: 'activity', evaluationDate: '2026-11-21', given: { context: { header: {} } }, expect: { outcome: 'done' } };
    const tkey = await draft(env, test);
    expect(env.store.entries.get(tkey)!.changeSet).toBe(id);
    const commits = log(env, `studio/${id}`);
    expect(commits.length).toBe(log(env).length + 3);
    expect(commits[0].message).toMatch(new RegExp(`^Draft CS-NOTE-001 \\(${id}\\)`));
    expect(commits.every((c) => c.author === 'TransactHub Studio' || c.sha === head || log(env).some((x) => x.sha === c.sha))).toBe(true);
    const branchFiles = files(env, `studio/${id}`);
    expect(branchFiles[`${ROOT}/artefacts/p/p.enrich.cs-note-a.v1/1.0.0.yaml`]).toMatch(/title: Note, saved again/);
    expect(branchFiles[`${ROOT}/audit/change-sets/${id}.yaml`]).toMatch(/action: save-draft/);

    const again = await restart(env);
    expect(again.store.drafts('owner').map((d) => [d.key, d.changeSet, d.status])).toEqual(expect.arrayContaining([[key, id, 'draft'], [tkey, id, 'draft']]));
    expect(again.store.entries.get(key)!.doc.title).toBe('Note, saved again');
    expect(again.store.audit.filter((a) => a.changeSet === id).map((a) => a.actor)).toEqual(['shared.designer', 'shared.designer', 'shared.designer']);
  });

  it('approval publishes the change set into the content branch as one commit, which takes its branch in', async () => {
    const env = freshEnv();
    const key = await draft(env, ACT('b'));
    const id = env.store.entries.get(key)!.changeSet!;
    await call(env, 'POST', '/api/review', { tenant: 'owner', actor: 'shared.designer', key });
    const before = log(env).length;
    const draftHead = log(env, `studio/${id}`)[0].sha;
    const pub = await publish(env, key);
    expect(pub.changeSet.id).toBe(id);
    expect(pub.git).toMatchObject({ status: 'committed', branch: BRANCH, changeSet: id });
    expect(pub.git.files.sort()).toEqual([`${ROOT}/artefacts/p/p.enrich.cs-note-b.v1/1.0.0.yaml`, `${ROOT}/audit/change-sets/${id}.yaml`, `${ROOT}/change-sets/${id}.yaml`]);
    const l = log(env);
    expect(l.length).toBe(before + 1);
    expect(l[0].parents).toEqual([l[1].sha, draftHead]);
    expect(l[0].message).toMatch(new RegExp(`^Release change set ${id}: 1 artefact[\\s\\S]*Maker: shared\\.designer\\nChecker: shared\\.checker`));
    expect(l[0].sha).toBe(pub.git.commit);
    expect(fake().forced).toBe(0);

    const again = await restart(env);
    expect(again.store.get('p.enrich.cs-note-b.v1', '1.0.0')).toMatchObject({ status: 'published', source: 'studio', maker: 'shared.designer', checker: 'shared.checker' });
    expect(again.store.drafts('owner')).toEqual([]);
    expect((again.store.extra.changeSets ?? []).map((c: any) => c.id)).toContain(id);
  });

  it('in pull-request mode, approval opens a pull request from the change set branch and leaves the content branch alone', async () => {
    const env = freshEnv();
    expect((await call(env, 'PUT', '/api/git', { actor: 'shared.designer', mode: 'pull-request' })).status).toBe(409);
    const s = await call(env, 'PUT', '/api/git', { actor: 'shared.checker', mode: 'pull-request' });
    expect(s.status, JSON.stringify(s.body)).toBe(200);
    expect(files(env)[`${ROOT}/governance/settings.yaml`]).toMatch(/mode: pull-request/);
    const key = await draft(env, ACT('c'));
    const id = env.store.entries.get(key)!.changeSet!;
    const head = log(env)[0].sha;
    const pub = await publish(env, key);
    expect(pub.git).toMatchObject({ status: 'pull-request', branch: `studio/${id}`, pullRequest: { opened: true, branch: `studio/${id}` } });
    expect(log(env)[0].sha).toBe(head);
    expect(files(env, `studio/${id}`)[`${ROOT}/change-sets/${id}.yaml`]).toBeDefined();
    expect(env.store.entries.get(key)).toMatchObject({ status: 'in-review', awaitingMerge: `studio/${id}` });
    expect((await publish(env, key).catch(() => undefined)) ?? 'refused').toBe('refused');
    const pulls = fake().repo(env.store.content!.repository).pulls;
    expect(pulls).toHaveLength(1);
    expect(pulls[0]).toMatchObject({ head: `studio/${id}`, base: BRANCH, title: `Release change set ${id}` });

    // Waiting for the merge survives a restart; once merged, the change set is published.
    expect((await restart(env)).store.entries.get(key)).toMatchObject({ status: 'in-review', awaitingMerge: `studio/${id}` });
    fake().mergePull(env.store.content!.repository, pulls[0].number);
    const merged = await restart(env);
    expect(merged.store.get('p.enrich.cs-note-c.v1', '1.0.0')?.status).toBe('published');
    expect(merged.store.drafts('owner')).toEqual([]);
  }, 60000);
});

// A call that must be refused: the expect in publish() would fail it, so call the API directly.
async function refused(env: any, key: string) {
  return call(env, 'POST', '/api/publish', { tenant: 'owner', key, checker: 'shared.checker' });
}

describe('append-only state files (R-11-23, R-09-21)', () => {
  it('keeps the audit as one file per change set and one per other event, and its chain verifies after a restart', async () => {
    const env = freshEnv();
    const refusedDraft = await call(env, 'POST', '/api/drafts', { tenant: 'owner', actor: 'example.maker', doc: ACT('d') });
    expect(refusedDraft.status).toBe(409);
    const key = await draft(env, ACT('d'));
    const id = env.store.entries.get(key)!.changeSet!;
    await publish(env, key);
    const paths = Object.keys(files(env)).filter((p) => p.startsWith(`${ROOT}/audit/`));
    expect(paths).toContain(`${ROOT}/audit/change-sets/${id}.yaml`);
    const events = paths.filter((p) => p.startsWith(`${ROOT}/audit/events/`));
    expect(events.length).toBe(1);
    expect(files(env)[events[0]]).toMatch(/outcome: refused[\s\S]*actor: example\.maker/);
    const again = await restart(env);
    expect(again.store.verifyAudit()).toEqual({ ok: true });
    expect(again.store.audit.filter((a) => a.changeSet === id).map((a) => a.action)).toEqual(['save-draft', 'publish', 'publish-change-set']);
  });

  it('never rewrites a published file: a clash stops the publish and names the file, and nothing is forced', async () => {
    const env = freshEnv();
    const key = await draft(env, ACT('e'));
    const repo = env.store.content!.repository;
    const theirs = fake().commitFiles(repo, BRANCH, { [`${ROOT}/artefacts/p/p.enrich.cs-note-e.v1/1.0.0.yaml`]: 'kind: activity\nname: p.enrich.cs-note-e.v1\nrelease: 1.0.0\ntitle: Written elsewhere\n' });
    const r = await refused(env, key);
    expect(r.status).toBe(409);
    expect(r.body.code).toBe('R-09-21');
    expect(r.body.error).toMatch(/content-configurations\/artefacts\/p\/p\.enrich\.cs-note-e\.v1\/1\.0\.0\.yaml.*never rewritten/);
    expect(fake().head(repo, BRANCH)).toBe(theirs);
    expect(fake().forced).toBe(0);
    // The studio read the branch again: the other writer's release is what it now holds.
    expect(env.store.get('p.enrich.cs-note-e.v1', '1.0.0')?.doc.title).toBe('Written elsewhere');
  });

  it('changes the users only through maker-checker: one file, replaced in one reviewed commit', async () => {
    const env = freshEnv();
    const list = [...(await call(env, 'GET', '/api/users')).body, { id: 'third.maker', tenant: 'third-bank', roles: ['bank designer'] }];
    expect((await call(env, 'POST', '/api/users/proposals', { actor: 'shared.designer', users: list })).status).toBe(409);
    const p = await call(env, 'POST', '/api/users/proposals', { actor: 'service.operations', users: list });
    expect(p.status, JSON.stringify(p.body)).toBe(200);
    const id = p.body.changeSet;
    expect(files(env, `studio/${id}`)[`${ROOT}/governance/users.yaml`]).toMatch(/third\.maker/);
    expect((await call(env, 'GET', '/api/users/proposals')).body.map((x: any) => x.id)).toEqual([id]);
    expect(files(env)[`${ROOT}/governance/users.yaml`]).not.toMatch(/third\.maker/);
    expect((await call(env, 'POST', `/api/users/proposals/${id}/approve`, { checker: 'service.operations' })).status).toBe(409);
    const before = log(env).length;
    const a = await call(env, 'POST', `/api/users/proposals/${id}/approve`, { checker: 'shared.checker' });
    expect(a.status, JSON.stringify(a.body)).toBe(200);
    expect(log(env).length).toBe(before + 1);
    expect(files(env)[`${ROOT}/governance/users.yaml`]).toMatch(/third\.maker/);
    expect(files(env)[`${ROOT}/change-sets/${id}.yaml`]).toMatch(/files:\n\s+- governance\/users\.yaml/);
    const again = await restart(env);
    expect(again.store.extra.users.map((u: any) => u.id)).toContain('third.maker');
    expect(again.store.extra.userProposals ?? []).toEqual([]);
  });

  it('a waiver goes with its change set; settings, in-flight counts and configuration sets are files of their own', async () => {
    const env = freshEnv();
    const w = await call(env, 'POST', '/api/conformance/waivers', { actor: 'shared.checker', target: 'studio', scenario: 'CK-SEQ-01', reason: 'A test waiver' });
    expect(w.status, JSON.stringify(w.body)).toBe(200);
    expect(files(env)[`${ROOT}/change-sets/${w.body.changeSet}.yaml`]).toMatch(/waivers:[\s\S]*scenario: CK-SEQ-01/);
    await call(env, 'POST', '/api/in-flight', { actor: 'service.operations', counts: { 'p.wf.commercial.v1@1.0.0': 2 }, asOf: '2026-11-21' });
    const cs = { ...env.store.configurationSet('example-bank'), release: '1.1.0' };
    const { toYaml } = await import('../src/core/yaml.js');
    const c = await call(env, 'POST', '/api/tenants/example-bank/configuration', { actor: 'example.maker', yaml: toYaml(cs) });
    expect(c.status, JSON.stringify(c.body)).toBe(200);
    const names = Object.keys(files(env));
    expect(names).toContain(`${ROOT}/banks/example-bank/configuration-sets/1.1.0.yaml`);
    expect(names.some((p) => p.startsWith(`${ROOT}/governance/in-flight/`))).toBe(true);
    const again = await restart(env);
    expect((await call(again, 'GET', '/api/conformance/report')).body.rows.find((r: any) => r.scenario === 'CK-SEQ-01')?.waiver?.reason).toBe('A test waiver');
    expect(again.store.extra.inFlight).toMatchObject({ asOf: '2026-11-21' });
    expect(again.store.configurationSet('example-bank').release).toBe('1.1.0');
    expect(again.store.get('config:example-bank', '1.1.0', 'example-bank')?.maker).toBe('example.maker');
  }, 60000);
});

describe('memory only, through the GitHub API (R-11-24)', () => {
  it('re-reads, rechecks and retries once when another writer moves the branch, then stops; it never forces', async () => {
    const env = freshEnv();
    const repo = env.store.content!.repository;
    const key = await draft(env, ACT('f'));
    let moves = 0;
    fake().beforeRefUpdate = (r, b) => {
      if (r !== repo || b !== BRANCH || moves++ > 0) return;
      fake().commitFiles(repo, BRANCH, { [`${ROOT}/notes/elsewhere.md`]: 'unrelated\n' });
    };
    try {
      await publish(env, key);
    } finally {
      fake().beforeRefUpdate = undefined;
    }
    expect(moves).toBe(2);
    expect(files(env)[`${ROOT}/notes/elsewhere.md`]).toBe('unrelated\n');
    expect(log(env)[1].message).toBe('An edit elsewhere');

    const key2 = await draft(env, ACT('g'));
    fake().beforeRefUpdate = (r, b) => {
      if (r === repo && b === BRANCH) fake().commitFiles(repo, BRANCH, { [`${ROOT}/notes/n-${Math.random()}.md`]: 'again\n' });
    };
    let r;
    try {
      r = await refused(env, key2);
    } finally {
      fake().beforeRefUpdate = undefined;
    }
    expect(r.status).toBe(409);
    expect(r.body).toMatchObject({ code: 'conflict' });
    expect(r.body.error).toMatch(/moved again while the studio wrote to it.*nothing was forced/);
    expect(fake().forced).toBe(0);
    // Nothing of the refused publish is on the branch, and the draft is still on its own.
    expect(env.store.entries.get(key2)?.status).toBe('draft');
    expect(files(env)[`${ROOT}/artefacts/p/p.enrich.cs-note-g.v1/1.0.0.yaml`]).toBeUndefined();
  });

  it('never stores, shows, logs or writes the token', async () => {
    const env = freshEnv();
    const key = await draft(env, ACT('h'));
    await publish(env, key);
    const status = await call(env, 'GET', '/api/git');
    expect(status.body.connection).toMatchObject({ repository: env.store.content!.repository, branch: BRANCH });
    const everything = JSON.stringify([status.body, env.store.audit, env.store.extra, files(env), env.store.content!.writes, env.store.content!.conn]);
    expect(everything).not.toContain(TEST_TOKEN);
    // A wrong token: GitHub's refusal is reported, and the token is not in it.
    const bad = 'synthetic-wrong-token';
    const err = await ContentStore.open(connection(fake(), forkRepo(), bad)).catch((e) => e);
    expect(err.message).toMatch(/401.*Bad credentials/);
    expect(err.message).not.toContain(bad);
  });

  it('does not start without TH_CONTENT_REPO', () => {
    const env = { ...process.env, TH_CONTENT_REPO: '', PORT: '0' };
    const r = spawnSync(path.join(STUDIO_ROOT, 'node_modules', '.bin', 'tsx'), ['src/server/main.ts'], { cwd: STUDIO_ROOT, env, encoding: 'utf8', timeout: 60000 });
    expect(r.status).toBe(1);
    expect(r.stderr).toMatch(/does not start: TH_CONTENT_REPO is not set/);
    expect(r.stderr).toMatch(/npm run studio:dev/);
  });
});

describe('the factory published into content (R-11-25)', () => {
  it('seeds once as one change set beside the runtime files; a second run changes nothing; the repository copy is current', async () => {
    const full = forkRepo();
    const seeded = seedFiles(SPEC_ROOT);
    const now = fake().files(full, BRANCH);
    // A branch as it was before the seed: the runtime files and DIB's configuration only.
    const remove: Record<string, null> = {};
    for (const p of Object.keys(now)) {
      const rel = p.slice(ROOT.length + 1);
      if (seeded.some((s) => s.path === rel) || /^(change-sets|audit|governance)\//.test(rel)) remove[p] = null;
    }
    fake().commitFiles(full, BRANCH, remove, 'Before the seed');
    const env = envFor(await ContentStore.open(connection(fake(), full)), { banks: [] });
    expect(env.store.get('p.wf.commercial.v1')).toBeUndefined();
    const before = fake().log(full, BRANCH).length;
    const r = await seedContent(env);
    expect(r.status).toBe('committed');
    expect(fake().log(full, BRANCH).length).toBe(before + 1);
    const after = fake().files(full, BRANCH);
    // Every seeded file is as this repository's content-configurations/ holds it, and the runtime files stay.
    for (const s of seeded) expect(after[`${ROOT}/${s.path}`], s.path).toBe(now[`${ROOT}/${s.path}`]);
    expect(after[`${ROOT}/banks/example-bank/core-banking.yaml`]).toBe(now[`${ROOT}/banks/example-bank/core-banking.yaml`]);
    expect(after[`${ROOT}/change-sets/${r.changeSet}.yaml`]).toMatch(/origin: seed/);
    expect(env.store.get('p.wf.commercial.v1')?.status).toBe('published');
    const again = await seedContent(env);
    expect(again).toMatchObject({ status: 'unchanged', added: [] });
    expect(fake().log(full, BRANCH).length).toBe(before + 1);
    // And this repository's copy needs no seeding: the generated files are current.
    expect(path.relative(STUDIO_ROOT, CONTENT_DIR)).toBe(path.join('..', 'content-configurations'));
    expect(await seedContent(freshEnv())).toMatchObject({ status: 'unchanged' });
  }, 60000);
});

