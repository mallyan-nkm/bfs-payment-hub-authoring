import ts from 'typescript';
import { spawnSync } from 'node:child_process';
import type { CanonicalModel, Element } from './model.js';
import { coveredByAny } from './paths.js';

// Types for scripts-behind (C03-S3, C03-S4): one context type per activity, from its declared
// reads and writes and the canonical model, in TypeScript and in Python. The type check gate
// refuses a script that touches a path its contract does not declare or the model does not hold.

const TS_PRIMITIVE: Record<string, string> = {
  ActiveCurrencyAndAmount: 'number', DecimalNumber: 'number', Number: 'number', Max15NumericText: 'number',
  StatusHistory: 'unknown[]', MessageReferences: 'Record<string, MessageRef>', MessageReference: 'MessageRef', BlockFact: 'Record<string, unknown>',
};
const PY_PRIMITIVE: Record<string, string> = { ActiveCurrencyAndAmount: 'float', DecimalNumber: 'float', Number: 'float', Max15NumericText: 'int', StatusHistory: 'list', MessageReferences: 'dict', MessageReference: 'MessageRef', BlockFact: 'dict' };

function pruned(model: CanonicalModel, paths: string[]): Element[] {
  const keep = (e: Element): Element | undefined => {
    const inside = paths.some((p) => coveredByAny([p], e.path));
    const above = paths.some((p) => coveredByAny([e.path], p));
    if (!inside && !above) return undefined;
    if (inside) return e;
    return { ...e, children: (e.children ?? []).map(keep).filter(Boolean) as Element[] };
  };
  return model.roots.map(keep).filter(Boolean) as Element[];
}

function tsType(e: Element, indent: string): string {
  if (!e.children?.length) return TS_PRIMITIVE[e.isoType] ?? 'string';
  const body = e.children.map((c) => `${indent}  /** ${c.isoType}${c.personalData ? ', personal data' : ''}${c.description ? `. ${c.description}` : ''} */\n${indent}  ${JSON.stringify(c.name.replace('[]', ''))}?: ${tsType(c, indent + '  ')};`).join('\n');
  const obj = `{\n${body}\n${indent}}`;
  return e.name === 'items[]' ? `Array<${obj}>` : obj;
}

/** The TypeScript context type of an activity, reproducibly from the same model (C03-S3). */
export function typescriptTypes(model: CanonicalModel, act: any): string {
  const roots = pruned(model, [...(act.reads ?? []), ...(act.writes ?? [])]);
  const lines = [
    `// Generated by the studio from ${act.name}@${act.release}: its declared reads and writes over the canonical model. Do not edit.`,
    'export interface MessageRef { id: string; type: string; payload?: string; malformed?: boolean }',
    `export interface Ctx {`,
    ...roots.map((r) => `  ${JSON.stringify(r.name.replace('[]', ''))}?: ${tsType(r, '  ')};`),
    '}',
    `export type Outcome = ${(act.outcomes ?? []).map((o: any) => JSON.stringify(o.name)).join(' | ') || 'string'};`,
    '',
  ];
  return lines.join('\n');
}

function pyClass(name: string, e: Element, out: string[]) {
  const fields: string[] = [];
  for (const c of e.children ?? []) {
    const n = c.name.replace('[]', '');
    if (c.children?.length) {
      const cls = `${name}_${n}`;
      pyClass(cls, c, out);
      fields.push(`    ${n}: ${c.name === 'items[]' ? `list[${cls}]` : cls}`);
    } else fields.push(`    ${n}: ${PY_PRIMITIVE[c.isoType] ?? 'str'}  # ${c.isoType}${c.personalData ? ', personal data' : ''}`);
  }
  out.push(`class ${name}(TypedDict, total=False):\n${fields.join('\n') || '    pass'}\n`);
}

/** The Python typed stubs of an activity (C03-S4). */
export function pythonTypes(model: CanonicalModel, act: any): string {
  const out: string[] = [`# Generated by the studio from ${act.name}@${act.release}. Do not edit.`, 'from typing import Literal, TypedDict', '', 'class MessageRef(TypedDict, total=False):\n    id: str\n    type: str\n    payload: str\n    malformed: bool\n'];
  pyClass('Ctx', { path: '', name: 'Ctx', isoType: 'Component', personalData: false, origin: 'iso', children: pruned(model, [...(act.reads ?? []), ...(act.writes ?? [])]) }, out);
  out.push(`Outcome = Literal[${(act.outcomes ?? []).map((o: any) => JSON.stringify(o.name)).join(', ')}]`, '');
  return out.join('\n');
}

export interface TypeIssue { path: string; message: string; line?: number }

/** Every ctx property chain a TypeScript script reads or writes. */
export function ctxPathsTs(source: string): { path: string; line: number }[] {
  const sf = ts.createSourceFile('s.ts', source, ts.ScriptTarget.ES2022, true);
  const out: { path: string; line: number }[] = [];
  const chain = (n: ts.Node): string[] | undefined => {
    if (ts.isIdentifier(n)) return n.text === 'ctx' ? [] : undefined;
    if (ts.isPropertyAccessExpression(n)) {
      const base = chain(n.expression);
      return base ? [...base, n.name.text] : undefined;
    }
    if (ts.isElementAccessExpression(n) && ts.isStringLiteral(n.argumentExpression)) {
      const base = chain(n.expression);
      return base ? [...base, n.argumentExpression.text] : undefined;
    }
    if (ts.isNonNullExpression(n) || ts.isParenthesizedExpression(n)) return chain(n.expression);
    return undefined;
  };
  const visit = (n: ts.Node) => {
    if ((ts.isPropertyAccessExpression(n) || ts.isElementAccessExpression(n)) && !(n.parent && (ts.isPropertyAccessExpression(n.parent) || ts.isElementAccessExpression(n.parent)) && (n.parent as any).expression === n)) {
      const c = chain(n);
      if (c && c.length) out.push({ path: c.join('.'), line: sf.getLineAndCharacterOfPosition(n.getStart()).line + 1 });
    }
    ts.forEachChild(n, visit);
  };
  visit(sf);
  return out;
}

/** Every api.ctx[...] chain a Python script reads or writes, with the Python parser. */
export function ctxPathsPy(source: string): { path: string; line: number }[] {
  const prog = `
import ast, json, sys
src = sys.stdin.read()
out = []
class V(ast.NodeVisitor):
    def chain(self, n):
        if isinstance(n, ast.Attribute) and n.attr == 'ctx' and isinstance(n.value, ast.Name) and n.value.id == 'api':
            return []
        if isinstance(n, ast.Subscript) and isinstance(n.slice, ast.Constant) and isinstance(n.slice.value, str):
            b = self.chain(n.value)
            return None if b is None else b + [n.slice.value]
        if isinstance(n, ast.Call) and isinstance(n.func, ast.Attribute) and n.func.attr == 'get' and n.args and isinstance(n.args[0], ast.Constant):
            b = self.chain(n.func.value)
            return None if b is None else b + [n.args[0].value]
        return None
    def generic_visit(self, n):
        c = self.chain(n)
        if c:
            out.append({'path': '.'.join(c), 'line': getattr(n, 'lineno', 0)})
            return
        super().generic_visit(n)
V().visit(ast.parse(src))
print(json.dumps(out))
`;
  const r = spawnSync(process.env.TH_PYTHON ?? 'python3', ['-I', '-c', prog], { input: source, encoding: 'utf8' });
  if (r.status !== 0) return [{ path: '', line: 0 }];
  return JSON.parse(r.stdout);
}

/**
 * The type check gate (C03-S3, C16-S1): a script may touch only paths under its declared reads and
 * writes, and only paths the canonical model holds.
 */
export function typeCheckScript(model: CanonicalModel, act: any, source: string, language: 'typescript' | 'python'): TypeIssue[] {
  const declared = [...(act.reads ?? []), ...(act.writes ?? [])];
  const used = language === 'python' ? ctxPathsPy(source) : ctxPathsTs(source);
  const issues: TypeIssue[] = [];
  for (const u of used) {
    if (!u.path) {
      issues.push({ path: '', message: 'The script does not parse' });
      continue;
    }
    const p = u.path.replace(/^items\.\d+/, 'items[]').replace(/^items(\.|$)/, 'items[]$1');
    const under = declared.some((d) => coveredByAny([d], p) || coveredByAny([p], d));
    if (!under) issues.push({ path: u.path, line: u.line, message: `ctx.${u.path} is not in the declared reads or writes of ${act.name}` });
    else if (!model.resolve(p) && !declared.some((d) => coveredByAny([d], p) && model.resolve(d)?.isoType === 'BlockFact') && !p.startsWith('facts.') && !p.startsWith('messages.')) {
      // Below a declared path the model must still hold the element.
      const parentDeclared = declared.find((d) => coveredByAny([d], p));
      if (parentDeclared && model.resolve(parentDeclared)?.children?.length) issues.push({ path: u.path, line: u.line, message: `ctx.${u.path} is not an element of the canonical model` });
    }
  }
  return issues;
}
