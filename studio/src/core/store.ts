// The artefact store (C01; R-11-08, R-11-21 to R-11-25). Every artefact and every piece of studio state
// is a file on the content branch of a GitHub repository, read into memory through the GitHub API
// (`ContentStore`). Drafts live on their change set's own branch, `studio/<change set id>`, one commit
// per save. Approval publishes the change set into the content branch as one commit. State (audit,
// users, settings, waivers) is files beside the content, append-only. Nothing is written to disk.
// A published release is immutable: a second write to the same name and release is refused.

export const OWNER_TENANT = 'owner';

/** Documents in a bank's folder that the runtime reads, not the studio: port bindings and configuration values. */
export const RUNTIME_KINDS = ['port-bindings', 'configuration-values'];

/** The first line of a file the seed command published: it names the file in `spec/` it came from (R-11-25). */
export const SEED_HEADER = /^# Generated by `npm run studio -- seed-content` from spec\/(\S+?\.ya?ml)\b/;
/** The first line of a factory script-behind or sample the seed published from `studio/` (R-11-25). */
export const SEED_SOURCE_HEADER = /^(?:#|\/\/) Generated by `npm run studio -- seed-content` from (studio\/\S+?)\. /;

export type Status = 'published' | 'draft' | 'in-review' | 'retired';

export interface Entry {
  key: string; // name@release, or id for tests, or scope for schemes and packs
  kind: string;
  name: string;
  release: string;
  scope: string;
  tenant: string;
  status: Status;
  doc: any;
  hash: string;
  path: string; // where it came from: its file in spec/ for seeded content, else its path on the content branch
  source: 'spec' | 'studio';
  generated: boolean;
  maker?: string;
  checker?: string;
  publishedAt?: string;
  /** A draft's change set, whose branch holds it (R-11-22). */
  changeSet?: string;
  /** Approved in pull-request mode: on its change set's branch, waiting for the pull request to merge (R-09-22). */
  awaitingMerge?: string;
}

export interface AuditEvent {
  at: string;
  tenant: string;
  actor: string;
  action: string;
  key: string;
  detail?: string;
  outcome?: 'done' | 'refused';
  diff?: any;
  /** The change set the event belongs to: its events are one file, `audit/change-sets/<id>.yaml`. */
  changeSet?: string;
  prevHash?: string;
  hash?: string; // each record hashes the one before it in its file, so the log cannot be changed unseen (C17-S4)
}

export interface Settings {
  /** `commit`: approval writes the content branch. `pull-request`: it opens a pull request from the change set's branch (R-09-22). */
  mode: 'commit' | 'pull-request';
  /** The engine whose package each published workflow carries under `releases/`. */
  target: string;
  /** When set, each publish also writes an activation for this environment. */
  environment?: string;
  changedBy?: string;
  changedAt?: string;
}

export const DEFAULT_SETTINGS: Settings = { mode: 'commit', target: 'temporal' };

export class StoreError extends Error {
  constructor(public code: string, message: string) {
    super(message);
  }
}

function scopeOfDoc(doc: any): string {
  if (typeof doc.scope === 'string') return doc.scope;
  if (doc.kind === 'supersession' && doc.artefact) return parseName(doc.artefact)?.scope ?? 'p';
  const n = doc.name ? parseName(doc.name) : null;
  if (n) return n.scope;
  if (doc.kind === 'test') {
    const t = doc.target ? parseName(doc.target) : null;
    return t?.scope ?? 'p';
  }
  if (doc.kind === 'configuration-set') return 'b';
  return 'p';
}

function nameOfDoc(doc: any): string {
  if (doc.kind === 'scheme') return `scheme:${doc.scope}`;
  if (doc.kind === 'pack') return `pack:${doc.scope}${doc.tenant ? ':' + doc.tenant : ''}`;
  if (doc.kind === 'inventory') return 'inventory';
  if (doc.kind === 'conformance-kit') return 'conformance-kit';
  return doc.name ?? doc.id ?? (doc.kind === 'configuration-set' ? `config:${doc.tenant}` : doc.kind === 'engine-binding' ? `binding:${doc.target}` : doc.scope ?? doc.kind);
}

/** A bank's own content is keyed by tenant, so two banks may use one name (C17-S1). */
export function tenantKey(doc: any, tenant: string): string {
  return (tenant && tenant !== OWNER_TENANT ? `${tenant}/` : '') + keyOf(doc);
}

export function keyOf(doc: any): string {
  const name = nameOfDoc(doc);
  return doc.release ? `${name}@${doc.release}` : name;
}

/** What other artefacts use to refer to a document: its name, or a scheme's scope and message ids. */
export function identifiers(doc: any): string[] {
  if (doc?.kind === 'scheme') return [doc.scope, ...(doc.messages ?? []).map((m: any) => m.id)];
  return [doc?.name ?? doc?.id].filter(Boolean);
}

export function mentions(doc: any, ids: string[]): boolean {
  const text = JSON.stringify(doc);
  return ids.some((id) => text.includes(`"${id}"`));
}

const GENESIS = 'sha256:' + '0'.repeat(64);
const hashOf = (body: any) => 'sha256:' + createHash('sha256').update(canonicalJson(body), 'utf8').digest('hex');
const streamOf = (e: AuditEvent) => e.changeSet ?? '';

export interface ScriptSource { name: string; language: 'typescript' | 'python'; source: string; file: string; changeSet?: string }

export class Store {
  entries = new Map<string, Entry>(); // key -> entry
  /** Studio state read from its files: change sets, users, waivers, in-flight counts, handed-over supersessions. */
  extra: Record<string, any> = {};
  /**
   * The audit the studio holds: what it read at start (the change sets in progress, the events its state
   * depends on, the newest event) and what it recorded since. `readAudit()` reads the rest (R-11-27).
   */
  audit: AuditEvent[] = [];
  /** Has every audit file of the branch been read? */
  private auditRead = false;
  settings: Settings = { ...DEFAULT_SETTINGS };
  /** Samples the seed published from the studio's fixtures: factory content, not a designer's (R-11-25). */
  readonly factorySamples = new Set<string>();
  /** Script-behinds on the branch (published) and on change set branches (drafts), by activity name. */
  readonly scriptSources = new Map<string, ScriptSource>();
  /** Synthetic samples on the branch: those a designer added, and a loaded bank's own. */
  readonly sampleFiles = new Map<string, string>();
  readonly specRoot: string;
  /** Where the store reads and writes. Absent for a deployed worker's store and an import's shadow: those write nothing. */
  content?: ContentStore;
  /** Bank folders loaded as bank packs, by tenant. */
  readonly bankPacks = new Map<string, string>();
  private publishing = new Set<string>();

  constructor(specRoot: string) {
    this.specRoot = path.resolve(specRoot);
  }

  /**
   * The studio's store over a content branch (R-11-21). The factory and the example bank are read from
   * the branch, where the seed command published them (R-11-25); a bank pack other than the example
   * bank's only when named. The conformance kit is the engines' fixture and stays in `spec/conformance`.
   */
  static fromContent(content: ContentStore, specRoot: string, opts: { banks?: string[] } = {}): Store {
    const s = new Store(specRoot);
    s.content = content;
    s.loadDir(path.join(s.specRoot, 'conformance'));
    s.readContent(opts.banks ?? []);
    return s;
  }

  /** A store over plain folders of YAML, as a deployed worker holds its artefacts. It writes nothing. */
  static fromDirs(dirs: string[]): Store {
    const s = new Store(dirs[0] ?? '.');
    for (const d of dirs) s.loadDir(d);
    return s;
  }

  /** A copy in memory that writes nothing: what an import's analysis works on. */
  shadow(): Store {
    const s = new Store(this.specRoot);
    for (const [k, e] of this.entries) s.entries.set(k, { ...e });
    s.extra = this.extra;
    s.audit = [...this.audit];
    s.auditRead = this.auditRead;
    s.settings = this.settings;
    for (const k of this.factorySamples) s.factorySamples.add(k);
    for (const [k, v] of this.scriptSources) s.scriptSources.set(k, v);
    for (const [k, v] of this.sampleFiles) s.sampleFiles.set(k, v);
    return s;
  }

  /** Wait until every write is on the branch; a failed write is reported here. */
  async flush(): Promise<void> {
    await this.content?.flush();
  }

  /** Read the branch again: what others published since, and every change set in progress. */
  async reload(): Promise<void> {
    if (!this.content) return;
    // The folders asked for; the example bank's is read whenever it is there (a seed may be regenerating it).
    const banks = [...this.bankPacks.values()].filter((f) => f !== 'example-bank');
    await this.content.reload();
    this.entries.clear();
    this.extra = {};
    this.audit = [];
    this.auditRead = false;
    this.settings = { ...DEFAULT_SETTINGS };
    this.scriptSources.clear();
    this.sampleFiles.clear();
    this.factorySamples.clear();
    this.bankPacks.clear();
    this.loadDir(path.join(this.specRoot, 'conformance'));
    this.readContent(banks);
  }

  private loadDir(dir: string) {
    if (!fs.existsSync(dir)) return;
    for (const f of walkYaml(dir)) {
      const text = fs.readFileSync(f, 'utf8');
      const generated = text.startsWith('# Generated by');
      for (const doc of parseYamlAll(text)) {
        if (!doc || typeof doc !== 'object') continue;
        this.add(doc, path.relative(this.specRoot, f), 'spec', generated, 'published');
      }
    }
  }

  // ------------------------------------------------------------- reading the branch

  private readContent(banks: string[]) {
    const c = this.content!;
    const files = [...c.files].sort(([a], [b]) => a.localeCompare(b));
    const wantBank = new Set(['example-bank', ...banks]);
    for (const b of banks) if (!c.files.has(`banks/${b}/pack.yaml`)) throw new StoreError('bank-pack', `No bank pack ${b} on ${c.repository} ${c.conn.branch}: there is no ${c.conn.root}/banks/${b}/pack.yaml`);
    const events: AuditEvent[] = [];
    for (const [p, text] of files) {
      const parts = p.split('/');
      if (p.startsWith('artefacts/') && isYaml(p)) this.loadFile(p, text, undefined);
      else if (p.startsWith('supersessions/') && parts.length === 2 && isYaml(p)) this.loadFile(p, text, undefined);
      else if (parts[0] === 'banks' && parts.length > 2) {
        const tenant = parts[1];
        if (BANK_STUDIO_FOLDERS.includes(parts[2])) {
          if (parts[2] === 'scripts') this.addScript(p, text);
          else if (isYaml(p)) this.loadFile(p, text, tenant);
        } else if (wantBank.has(tenant) && c.files.has(`banks/${tenant}/pack.yaml`)) {
          if (parts[2] === 'tests' && parts[3] === 'samples' && parts.length === 5) this.sampleFiles.set(parts[4], text);
        }
      } else if (/^change-sets\/[^/]+\.yaml$/.test(p)) {
        const cs = parseYamlAll(text)[0];
        if (cs?.kind === 'change-set') (this.extra.changeSets ??= []).push(cs);
      } else if (p.startsWith('audit/') && isYaml(p)) {
        const doc = parseYamlAll(text)[0];
        for (const ev of Array.isArray(doc?.events) ? doc.events : doc?.event ? [doc.event] : []) events.push(ev);
      } else if (p === USERS_PATH) this.extra.users = parseYamlAll(text)[0]?.users;
      else if (p === SETTINGS_PATH) this.settings = { ...DEFAULT_SETTINGS, ...(parseYamlAll(text)[0]?.settings ?? {}) };
      else if (p.startsWith('governance/in-flight/') && isYaml(p)) this.extra.inFlight = parseYamlAll(text)[0]?.inFlight; // the latest, by name
      else if (p.startsWith('supersessions/handed-over/') && isYaml(p)) (this.extra.supersessions ??= []).push(parseYamlAll(text)[0]);
      else if (parts[0] === 'samples' && parts.length === 2 && !parts[1].endsWith('.md')) this.addSample(parts[1], text);
      else if (parts[0] === 'scripts' && parts.length === 2) this.addScript(p, text);
    }
    // Bank packs: each in its own folder, as a bank's repository holds it (Issue I-43).
    for (const t of [...wantBank].sort()) if (c.files.has(`banks/${t}/pack.yaml`)) this.loadBankPack(t);
    // Change sets in progress: their branches.
    for (const d of [...c.drafts.values()].sort((a, b) => a.id.localeCompare(b.id))) {
      const awaiting = d.files.has(changeSetPath(d.id)) ? draftBranch(d.id) : undefined;
      for (const [p, text] of [...d.files].sort(([a], [b]) => a.localeCompare(b))) {
        const parts = p.split('/');
        if (p === changeSetAuditPath(d.id)) {
          // Read even when the change set is published: its drafts left on the branch need their makers.
          // The published file, read with the audit, holds the same records; each is kept once.
          events.push(...(parseYamlAll(text)[0]?.events ?? []));
        } else if ((p.startsWith('artefacts/') || (parts[0] === 'banks' && BANK_STUDIO_FOLDERS.includes(parts[2]) && parts[2] !== 'scripts')) && isYaml(p)) {
          const tenant = parts[0] === 'banks' ? parts[1] : OWNER_TENANT;
          for (const doc of parseYamlAll(text)) {
            if (!doc || typeof doc !== 'object') continue;
            const e = this.add(doc, p, 'studio', false, 'draft', tenant);
            e.changeSet = d.id;
            if (awaiting) e.awaitingMerge = awaiting;
          }
        } else if (parts.at(-2) === 'scripts') this.addScript(p, text, d.id);
        else if (p === USERS_PATH && !c.published(d.id)) {
          const maker = (parseYamlAll(d.files.get(changeSetAuditPath(d.id)) ?? '')[0]?.events ?? []).find((a: any) => a.action === 'propose-users')?.actor;
          (this.extra.userProposals ??= []).push({ id: d.id, maker, users: parseYamlAll(text)[0]?.users });
        }
      }
    }
    this.audit = orderAudit(events);
    for (const cs of this.extra.changeSets ?? []) for (const w of cs.waivers ?? []) (this.extra.waivers ??= []).push(w);
    (this.extra.changeSets ?? []).sort((a: any, b: any) => String(a.publishedAt).localeCompare(String(b.publishedAt)) || String(a.id).localeCompare(String(b.id)));
    this.applyAudit();
  }

  /** What the audit says about the entries: makers, checkers, review states and retirements. */
  private applyAudit() {
    const byKey = new Map<string, AuditEvent[]>();
    for (const a of this.audit) byKey.set(a.key, [...(byKey.get(a.key) ?? []), a]);
    for (const cs of this.extra.changeSets ?? []) {
      for (const m of cs.members ?? []) {
        const e = this.entries.get(m.key);
        if (!e || e.source !== 'studio') continue;
        e.checker = cs.checker;
        e.publishedAt = cs.publishedAt;
        // The record names each member's maker; an older record only the change set's makers.
        e.maker = m.maker ?? (byKey.get(`${m.key}#draft`) ?? []).filter((a) => a.action === 'save-draft' && a.outcome !== 'refused').pop()?.actor ?? cs.makers?.[0];
      }
    }
    for (const e of this.entries.values()) {
      const evs = (byKey.get(e.key) ?? []).filter((a) => a.outcome !== 'refused');
      if (e.status === 'draft') {
        const last = evs.filter((a) => a.action === 'save-draft' || a.action === 'submit-for-review').pop();
        if (last?.action === 'submit-for-review' || e.awaitingMerge) e.status = 'in-review';
      } else if (e.status === 'published') {
        if (evs.some((a) => a.action === 'retire')) e.status = 'retired';
        if (!e.maker && e.source === 'studio') e.maker = evs.find((a) => a.action === 'set-configuration')?.actor;
      }
    }
  }

  private addScript(p: string, text: string, changeSet?: string) {
    const m = /([^/]+)\.(ts|js|py)$/.exec(p);
    if (!m) return;
    // A factory script the seed published carries a first line naming its source; the script is the rest.
    const source = SEED_SOURCE_HEADER.test(text) ? text.slice(text.indexOf('\n') + 1) : text;
    this.scriptSources.set(m[1], { name: m[1], language: m[2] === 'py' ? 'python' : 'typescript', source, file: `content:${p}`, changeSet });
  }

  /** A sample on the branch. One the seed published from the studio's fixtures is factory content (R-11-25). */
  private addSample(name: string, text: string) {
    if (SEED_SOURCE_HEADER.test(text)) {
      this.factorySamples.add(name);
      this.sampleFiles.set(name, text.slice(text.indexOf('\n') + 1));
    } else this.sampleFiles.set(name, text);
  }

  /** A file of the branch: a seeded file names its source in spec/, the rest are the studio's own. */
  private loadFile(p: string, text: string, tenant: string | undefined) {
    const seed = SEED_HEADER.exec(text);
    const body = seed ? text.slice(text.indexOf('\n') + 1) : text;
    for (const doc of parseYamlAll(body)) {
      if (!doc || typeof doc !== 'object') continue;
      if (seed) this.add(doc, seed[1], 'spec', body.startsWith('# Generated by'), 'published', tenant);
      else this.add(doc, p, 'studio', false, 'published', tenant);
    }
  }

  /**
   * A bank pack in its own folder on the branch, `banks/<bank>/` (Issue I-43). Its `pack.yaml` names the
   * tenant, and every document in the folder is that tenant's. The runtime's own formats there (port
   * bindings and configuration values) are not studio artefacts and stay out of the store.
   */
  loadBankPack(folder: string): string {
    const c = this.content!;
    const dir = `banks/${folder}/`;
    const packFile = `${dir}pack.yaml`;
    const text = c.files.get(packFile);
    if (text === undefined) throw new StoreError('bank-pack', `${c.conn.root}/${dir} has no pack.yaml`);
    const pack = parseYamlAll(SEED_HEADER.test(text) ? text.slice(text.indexOf('\n') + 1) : text)[0];
    if (pack?.kind !== 'pack' || pack.packType !== 'bank' || pack.scope !== 'b' || typeof pack.tenant !== 'string' || !pack.tenant || pack.tenant === OWNER_TENANT) {
      throw new StoreError('bank-pack', `${c.conn.root}/${packFile} is not a bank pack: it needs kind pack, packType bank, scope b and a tenant`);
    }
    for (const [p, t] of [...c.files].filter(([p]) => p.startsWith(dir) && isYaml(p) && !BANK_STUDIO_FOLDERS.includes(p.split('/')[2])).sort(([a], [b]) => a.localeCompare(b))) {
      const seed = SEED_HEADER.exec(t);
      const body = seed ? t.slice(t.indexOf('\n') + 1) : t;
      for (const doc of parseYamlAll(body)) {
        if (!doc || typeof doc !== 'object' || RUNTIME_KINDS.includes(doc.kind)) continue;
        if (doc.tenant && doc.tenant !== pack.tenant) throw new StoreError('bank-pack', `${c.conn.root}/${p} names tenant ${doc.tenant}, but its pack is ${pack.tenant}'s`);
        this.add(doc, seed ? seed[1] : p, 'spec', body.startsWith('# Generated by'), 'published', pack.tenant);
      }
    }
    this.bankPacks.set(pack.tenant, folder);
    return pack.tenant;
  }

  private tenantOfDoc(doc: any, file: string): string {
    if (doc.tenant) return doc.tenant;
    if (file.includes(`examples${path.sep}bank`)) return 'example-bank';
    return OWNER_TENANT;
  }

  add(doc: any, file: string, source: 'spec' | 'studio', generated: boolean, status: Status, tenant?: string): Entry {
    const name = nameOfDoc(doc);
    const e: Entry = {
      key: tenantKey(doc, tenant ?? this.tenantOfDoc(doc, file)) + (status === 'draft' ? '#draft' : ''),
      kind: doc.kind,
      name,
      release: doc.release ?? '',
      scope: scopeOfDoc(doc),
      tenant: tenant ?? this.tenantOfDoc(doc, file),
      status,
      doc,
      hash: contentHash(doc),
      path: file,
      source,
      generated,
    };
    this.entries.set(e.key, e);
    return e;
  }

  // ---------------------------------------------------------------- queries

  all(): Entry[] {
    return [...this.entries.values()];
  }

  /** What a tenant may see: shared content and its own (R-06-01). */
  visible(tenant: string): Entry[] {
    return this.all().filter((e) => e.tenant === OWNER_TENANT || e.tenant === tenant);
  }

  tenants(): string[] {
    const t = new Set<string>([OWNER_TENANT]);
    for (const e of this.all()) t.add(e.tenant);
    return [...t];
  }

  releasesOf(name: string, opts: { includeDrafts?: boolean; tenant?: string } = {}): Entry[] {
    return this.all()
      .filter((e) => e.name === name && (opts.includeDrafts || e.status === 'published'))
      .filter((e) => !opts.tenant || e.tenant === OWNER_TENANT || e.tenant === opts.tenant)
      .sort((a, b) => compareReleases(a.release, b.release));
  }

  /** The latest published release of a major line. */
  latest(name: string, tenant?: string): Entry | undefined {
    const r = this.releasesOf(name, { tenant });
    return r[r.length - 1];
  }

  get(name: string, release?: string, tenant?: string): Entry | undefined {
    // A pack manifest names its scheme manifest `<scope>.scheme`.
    if (name.endsWith('.scheme') && !this.entries.has(`${name}@${release}`)) return this.get(`scheme:${name.slice(0, -'.scheme'.length)}`, release, tenant);
    if (release) {
      const own = this.entries.get(`${name}@${release}`);
      if (own) return own;
      if (tenant) return this.entries.get(`${tenant}/${name}@${release}`);
      return this.all().find((e) => e.name === name && e.release === release && (e.status === 'published' || e.status === 'retired'));
    }
    return this.latest(name, tenant) ?? this.entries.get(name);
  }

  doc(name: string, release?: string, tenant?: string): any {
    return this.get(name, release, tenant)?.doc;
  }

  byKind(kind: string): Entry[] {
    return this.all().filter((e) => e.kind === kind && e.status === 'published');
  }

  test(id: string): Entry | undefined {
    return this.byKind('test').find((e) => e.name === id);
  }

  scheme(scope: string): any {
    return this.byKind('scheme').find((e) => e.scope === scope)?.doc;
  }

  configurationSet(tenant: string): any {
    const sets = this.byKind('configuration-set').filter((e) => e.doc.tenant === tenant);
    sets.sort((a, b) => compareReleases(a.release, b.release));
    return sets[sets.length - 1]?.doc;
  }

  // ------------------------------------------------------------------ writing

  private write(branch: string, message: string, changes: Change[], opts?: Parameters<ContentStore['write']>[3]): Promise<WriteResult> | undefined {
    return this.content?.write(branch, message, changes, opts);
  }

  private get contentBranch(): string {
    return this.content?.conn.branch ?? '';
  }

  /** Group every write made in `fn` into one commit per branch: an approval is one commit. */
  transaction<T>(fn: () => T): T {
    return this.content ? this.content.transaction(fn) : fn();
  }

  // -------------------------------------------------------------- authoring

  /** Who may author in a scope (R-06-03): a bank tenant only in `b`; the owner only in shared scopes. */
  assertMayAuthor(tenant: string, doc: any) {
    const scope = scopeOfDoc(doc);
    if (tenant !== OWNER_TENANT && isShared(scope) && doc.kind !== 'configuration-set') {
      throw new StoreError('R-06-03', `Tenant ${tenant} may not create or change ${keyOf(doc)}: shared content is read-only to a bank`);
    }
    if (tenant === OWNER_TENANT && !isShared(scope)) {
      throw new StoreError('R-06-03', `The owner tenant does not author bank content (${keyOf(doc)})`);
    }
  }

  /** The change set a new draft joins: its own if saved before, else the first open one of the tenant it refers to or that refers to it, else a new one. */
  private changeSetForNew(tenant: string, doc: any, key: string, asked?: string): string {
    const own = this.entries.get(key);
    if (own?.changeSet) return own.changeSet;
    if (asked) return asked;
    const ids = identifiers(doc);
    const open = this.drafts(tenant).filter((d) => d.changeSet && !d.awaitingMerge).sort((a, b) => a.changeSet!.localeCompare(b.changeSet!));
    const related = open.find((d) => mentions(doc, identifiers(d.doc)) || mentions(d.doc, ids));
    if (related) return related.changeSet!;
    return this.content?.allocateChangeSetId() ?? `CS-${new Date().toISOString().slice(0, 10)}-local`;
  }

  /** Save a draft: a commit on its change set's branch, `studio/<id>` (R-11-22). */
  saveDraft(tenant: string, actor: string, doc: any, opts: { changeSet?: string } = {}): Entry {
    this.assertMayAuthor(tenant, doc);
    // A test case is keyed by its id and carries no release (test-case.schema.json).
    if (doc.kind !== 'test' && (!doc.release || !parseRelease(doc.release))) throw new StoreError('R-01-08', 'A draft needs a release major.minor.patch');
    const published = this.entries.get(tenantKey(doc, tenant));
    if (published) throw new StoreError('R-01-11', `${keyOf(doc)} is published and immutable. Release a new one.`);
    const draftKey = tenantKey(doc, tenant) + '#draft';
    const prior = this.entries.get(draftKey);
    if (prior?.awaitingMerge) throw new StoreError('R-09-22', `${keyOf(doc)} is approved and waiting for its pull request on ${prior.awaitingMerge} to merge`);
    const cs = this.changeSetForNew(tenant, doc, draftKey, opts.changeSet);
    const p = documentPath(doc, tenant);
    const e = this.add(clone(doc), p, 'studio', false, 'draft', tenant);
    e.changeSet = cs;
    this.transaction(() => {
      this.write(draftBranch(cs), `Draft ${e.key.replace(/#draft$/, '')} (${cs})\n\nSaved by ${actor}.`, [{ path: p, text: toYaml(doc), guard: 'free' }]);
      this.record({ tenant, actor, action: 'save-draft', key: e.key, changeSet: cs });
    });
    return e;
  }

  drafts(tenant: string): Entry[] {
    return this.all().filter((e) => (e.status === 'draft' || e.status === 'in-review') && e.tenant === tenant);
  }

  deleteDraft(tenant: string, actor: string, key: string) {
    const e = this.entries.get(key);
    if (!e || e.status !== 'draft' || e.tenant !== tenant) throw new StoreError('not-found', `No draft ${key} in ${tenant}`);
    this.entries.delete(key);
    this.transaction(() => {
      if (e.changeSet) this.write(draftBranch(e.changeSet), `Delete draft ${key.replace(/#draft$/, '')} (${e.changeSet})`, [{ path: e.path, text: null, guard: 'free' }]);
      this.record({ tenant, actor, action: 'delete-draft', key, changeSet: e.changeSet });
    });
  }

  /** A script-behind of an activity draft: a file on the draft's change set branch. */
  saveScriptSource(tenant: string, actor: string, activity: string, language: 'typescript' | 'python', source: string) {
    const draft = this.drafts(tenant).find((d) => d.name === activity && d.kind === 'activity');
    const cs = draft?.changeSet;
    const p = scriptPath(tenant, activity, language);
    this.scriptSources.set(activity, { name: activity, language, source, file: `content:${p}`, changeSet: cs });
    this.transaction(() => {
      if (cs) this.write(draftBranch(cs), `Script ${activity} (${cs})`, [{ path: p, text: source, guard: 'free' }]);
      this.record({ tenant, actor, action: 'save-script', key: activity, detail: p.split('/').pop(), changeSet: cs });
    });
    return p;
  }

  /** A synthetic sample for tests: one file on the content branch, never rewritten. */
  saveSampleFile(tenant: string, actor: string, name: string, content: string) {
    const prior = this.sampleFiles.get(name);
    if (prior !== undefined && prior !== content) throw new StoreError('R-11-23', `samples/${name} is on the branch with other content; a published file is never rewritten. Choose another name.`);
    this.sampleFiles.set(name, content);
    this.transaction(() => {
      this.write(this.contentBranch, `Sample ${name}\n\nAdded by ${actor} (${tenant}).`, [{ path: `samples/${name}`, text: content, guard: 'create' }]);
      this.record({ tenant, actor, action: 'save-sample', key: `samples/${name}` });
    });
  }

  /** Publish one draft through maker-checker (R-06-04): a change set of one. */
  publish(tenant: string, draftKey: string, maker: string, checker: string): Entry {
    const d = this.entries.get(draftKey);
    if (!d || (d.status !== 'draft' && d.status !== 'in-review') || d.tenant !== tenant) throw new StoreError('not-found', `No draft ${draftKey} in ${tenant}`);
    if (!maker || !checker || maker === checker) {
      this.record({ tenant, actor: checker || maker, action: 'publish', key: draftKey, outcome: 'refused', detail: 'Maker and checker must differ (R-06-04)', changeSet: d.changeSet });
      throw new StoreError('R-06-04', 'Maker and checker must differ');
    }
    return this.transaction(() => {
      const id = this.changeSetIdFor([d]);
      const e = this.promote(tenant, draftKey, maker, checker, id);
      const changeSet = { id, tenant, checker, publishedAt: e.publishedAt!, makers: [maker], members: [{ kind: e.kind, name: e.name, release: e.release, key: e.key, maker }] };
      this.commitChangeSet(changeSet, [d.changeSet!].filter(Boolean), {});
      return e;
    });
  }

  /**
   * The id a change set publishes under (Issue I-44): the branch of the draft the checker approved,
   * `first`, else the first of its members' branches; a new id when that one is already published.
   */
  changeSetIdFor(drafts: Entry[], first?: string): string {
    const ids = [...new Set(drafts.map((d) => d.changeSet).filter(Boolean) as string[])].sort((a, b) => (a === first ? -1 : b === first ? 1 : a.localeCompare(b)));
    const own = ids.find((id) => !this.content?.published(id));
    return own ?? this.content?.allocateChangeSetId() ?? `CS-${new Date().toISOString().slice(0, 10)}-local`;
  }

  /** A draft becomes a published release in memory; its commit is the change set's (commitChangeSet). */
  promote(tenant: string, draftKey: string, maker: string, checker: string, changeSet: string): Entry {
    const d = this.entries.get(draftKey);
    if (!d) throw new StoreError('not-found', `No draft ${draftKey} in ${tenant}`);
    const key = tenantKey(d.doc, tenant);
    if (this.entries.has(key)) throw new StoreError('R-01-11', `${key} is already published. A published release is immutable.`);
    this.entries.delete(draftKey);
    const e = this.add(d.doc, d.path, 'studio', false, 'published', tenant);
    e.maker = maker;
    e.checker = checker;
    e.publishedAt = new Date().toISOString();
    const prev = this.releasesOf(e.name).filter((x) => x.key !== e.key).pop();
    this.publishing.add(changeSet);
    this.record({ tenant, actor: checker, action: 'publish', key, detail: `maker ${maker}, checker ${checker}`, diff: prev ? leafDiff(prev.doc, e.doc) : { created: true }, changeSet });
    return e;
  }

  /**
   * Write a published change set (R-11-19, R-11-22): in commit mode one commit on the content branch,
   * in pull-request mode one commit on the change set's branch and a pull request into the content
   * branch (R-09-22). The commit holds every member at its path, the scripts of the members, the change
   * set record, its audit and `extra` (engine packages, an activation). Every path is new: a file that
   * is on the branch with other content stops the publish and is named (R-09-21).
   */
  commitChangeSet(changeSet: any, branches: string[], extraFiles: Record<string, string | Change>, message?: string, opts: { pullRequest?: boolean } = {}): Promise<WriteResult> | undefined {
    const changes: Change[] = [];
    const add = (p: string, text: string) => changes.push({ path: p, text, guard: 'create' });
    const members = changeSet.members.map((m: any) => this.entries.get(m.key)).filter(Boolean) as Entry[];
    for (const e of members) {
      add(e.path.startsWith('artefacts/') || e.path.startsWith('banks/') ? e.path : documentPath(e.doc, e.tenant), toYaml(e.doc));
      const sc = this.scriptSources.get(e.name);
      if (sc && sc.changeSet && branches.includes(sc.changeSet)) {
        add(sc.file.replace(/^content:/, ''), sc.source);
        if (!opts.pullRequest) sc.changeSet = undefined;
      }
    }
    for (const [p, t] of Object.entries(extraFiles)) {
      if (typeof t === 'string') add(p, t);
      else changes.push({ ...t, path: p });
    }
    const record = toYaml({ kind: 'change-set', ...changeSet });
    add(changeSetPath(changeSet.id), record);
    const msg = message ?? `Release change set ${changeSet.id}: ${changeSet.members.length} artefact${changeSet.members.length === 1 ? '' : 's'}`;
    // The branches the publish empties: every draft on them is a member (R-11-22, R-11-26). The change
    // set's branch is merged in when the publish takes everything on it.
    const emptied = branches.filter((b) => !this.all().some((x) => x.changeSet === b && !members.includes(x) && (x.status === 'draft' || x.status === 'in-review')));
    const whole = branches.length === 1 && emptied.length === 1;
    // The audit of another branch this publish empties goes with its drafts, so that nothing is left only
    // there. A branch that keeps drafts keeps its audit, which publishes with them later.
    for (const b of emptied) {
      if (b === changeSet.id || this.content?.has(changeSetAuditPath(b))) continue;
      const events = this.audit.filter((a) => a.changeSet === b);
      if (events.length) add(changeSetAuditPath(b), toYaml({ kind: 'audit', changeSet: b, events }));
    }
    const target = opts.pullRequest && branches[0] ? draftBranch(branches[0]) : this.contentBranch;
    this.publishing.add(changeSet.id);
    this.record({ tenant: changeSet.tenant, actor: changeSet.checker, action: 'publish-change-set', key: changeSet.id, detail: changeSet.members.length > 20 ? `${changeSet.members.length} members, listed in ${changeSetPath(changeSet.id)}` : changeSet.members.map((m: any) => m.key).join(', '), changeSet: changeSet.id });
    let r: Promise<WriteResult> | undefined;
    this.transaction(() => {
      r = this.write(target, msg, changes, {
        merge: !opts.pullRequest && whole ? () => this.content?.drafts.get(branches[0])?.head : undefined,
        prune: opts.pullRequest ? undefined : emptied,
        pull: opts.pullRequest ? { title: `Release change set ${changeSet.id}`, body: `${msg}\n\nApproved in the studio through maker-checker. Merge the pull request to publish it.` } : undefined,
      });
      // The audit of the change set goes with it.
      this.writeChangeSetAudit(changeSet.id, target);
    });
    this.publishing.delete(changeSet.id);
    if (opts.pullRequest) {
      // Not published until the pull request merges: the members wait on their branch, in review.
      for (const e of members) {
        this.entries.delete(e.key);
        const d = this.add(e.doc, e.path, 'studio', false, 'draft', e.tenant);
        d.status = 'in-review';
        d.changeSet = branches[0];
        d.awaitingMerge = target;
      }
      (this.extra.pendingChangeSets ??= []).push({ ...changeSet, branch: target });
    } else (this.extra.changeSets ??= []).push(changeSet);
    return r;
  }

  /** The events of a change set that is published in this transaction go with it, not to its branch. */
  markPublishing(id: string) {
    this.publishing.add(id);
  }

  /** A proposed change to a state file (the users): a change set whose branch holds the new file (R-11-23). */
  proposeStateFile(p: string, doc: any, maker: string, action: string, key: string): string {
    const id = this.changeSetIdFor([]);
    this.transaction(() => {
      this.write(draftBranch(id), `Propose ${p} (${id})\n\nProposed by ${maker}.`, [{ path: p, text: toYaml(doc), guard: 'free' }]);
      this.record({ tenant: OWNER_TENANT, actor: maker, action, key, changeSet: id });
    });
    if (p === USERS_PATH) (this.extra.userProposals ??= []).push({ id, maker, users: doc.users });
    return id;
  }

  /** Approve a proposed state file: it replaces the one on the content branch in one commit, with its change set record and audit. */
  approveStateFile(id: string, p: string, doc: any, maker: string, checker: string, action: string) {
    const before = this.content?.files.get(p) ?? null;
    const changeSet = { id, tenant: OWNER_TENANT, checker, publishedAt: new Date().toISOString(), makers: [maker], members: [], files: [p] };
    this.transaction(() => {
      this.markPublishing(id);
      this.record({ tenant: OWNER_TENANT, actor: checker, action, key: p, detail: `maker ${maker}, checker ${checker}`, changeSet: id });
      this.commitChangeSet(changeSet, [id], { [p]: { path: p, text: toYaml(doc), guard: 'replace', expect: before } }, `Change ${p} (${id})\n\nMaker: ${maker}\nChecker: ${checker}`);
    });
  }

  private writeChangeSetAudit(id: string, branch: string) {
    const events = this.audit.filter((a) => a.changeSet === id);
    const text = toYaml({ kind: 'audit', changeSet: id, events });
    this.write(branch, `Audit of ${id}`, [{ path: changeSetAuditPath(id), text, guard: branch === this.contentBranch ? 'create' : 'free' }]);
  }

  /** Record an event (R-11-12). A change set's event goes into its file; any other is a file of its own. */
  record(ev: Omit<AuditEvent, 'at' | 'hash' | 'prevHash'>) {
    let changeSet = ev.changeSet ?? this.changeSetOfKey(ev.key);
    // A change set's file is closed once it is published: a later event about it is an event of its own,
    // which names the change set in its detail (R-11-23).
    if (changeSet && this.content?.published(changeSet) && !this.publishing.has(changeSet)) {
      ev = { ...ev, changeSet: undefined, detail: [ev.detail, `change set ${changeSet}`].filter(Boolean).join('; ') };
      changeSet = undefined;
    }
    const stream = changeSet ?? '';
    const prevHash = [...this.audit].reverse().find((a) => streamOf(a) === stream)?.hash ?? GENESIS;
    const body: any = { at: new Date().toISOString(), outcome: 'done' as const, ...ev, prevHash };
    if (changeSet) body.changeSet = changeSet;
    else delete body.changeSet;
    const hash = hashOf(body);
    const rec = { ...body, hash };
    this.audit.push(rec);
    if (!this.content) return;
    if (changeSet && this.publishing.has(changeSet)) return; // written with the change set
    if (changeSet) {
      this.writeChangeSetAudit(changeSet, draftBranch(changeSet));
      return;
    }
    this.write(this.contentBranch, `Audit: ${ev.action} ${ev.key}${ev.outcome === 'refused' ? ' (refused)' : ''}\n\nBy ${ev.actor} (${ev.tenant}).`, [{ path: eventAuditPath(rec.at, hash, ev.action), text: toYaml({ kind: 'audit', event: rec }), guard: 'create' }]);
  }

  private changeSetOfKey(key: string): string | undefined {
    const first = String(key ?? '').split(',')[0];
    const e = this.entries.get(first) ?? this.entries.get(`${first}#draft`);
    if (e?.changeSet && (e.status === 'draft' || e.status === 'in-review')) return e.changeSet;
    if (this.content?.drafts.has(first) && !this.content.published(first)) return first;
    return undefined;
  }

  /**
   * The whole audit: the audit files not read at start are read now, once, and cached by blob SHA
   * (R-11-27). An event already held keeps its place; the files are merged by time.
   */
  async readAudit(): Promise<AuditEvent[]> {
    if (this.auditRead || !this.content) return this.audit;
    const texts = await this.content.readUnread();
    const held = new Set(this.audit.map((a) => a.hash));
    const more: AuditEvent[] = [];
    for (const [p, text] of texts) {
      if (!isYaml(p)) continue;
      const doc = parseYamlAll(text)[0];
      for (const ev of Array.isArray(doc?.events) ? doc.events : doc?.event ? [doc.event] : []) if (ev && !held.has(ev.hash)) more.push(ev);
    }
    // A change set branch's file is replaced by the published one: keep one copy of each record.
    this.audit = orderAudit([...this.audit, ...more]);
    this.auditRead = true;
    return this.audit;
  }

  /** Verify the whole audit: in each file, every record hashes the one before it. */
  async verifyAudit(): Promise<{ ok: boolean; brokenAt?: number }> {
    await this.readAudit();
    const prev = new Map<string, string>();
    for (let i = 0; i < this.audit.length; i++) {
      const { hash, ...body } = this.audit[i];
      const s = streamOf(this.audit[i]);
      if (body.prevHash !== (prev.get(s) ?? GENESIS)) return { ok: false, brokenAt: i };
      if (hashOf(body) !== hash) return { ok: false, brokenAt: i };
      prev.set(s, hash!);
    }
    return { ok: true };
  }

  /** Move a draft to review, or a review back to draft (C19-S2). The event the caller records says so on the branch. */
  setState(key: string, status: Status) {
    const e = this.entries.get(key);
    if (!e) throw new StoreError('not-found', `No ${key}`);
    e.status = status;
    return e;
  }

  /** Retire a published release (C19-S3). The caller checks that nothing pins it. The event is the record. */
  retire(name: string, release: string, actor: string, tenant: string) {
    const e = this.get(name, release, tenant);
    if (!e || e.status !== 'published') throw new StoreError('not-found', `${name}@${release} is not published`);
    e.status = 'retired';
    this.record({ tenant, actor, action: 'retire', key: e.key });
    return e;
  }

  /** A document the studio publishes without a change set (a configuration set, C18-S2): one new file and its event. */
  publishDirect(doc: any, tenant: string, actor: string, ev: Omit<AuditEvent, 'at' | 'hash' | 'prevHash' | 'tenant' | 'actor'>): Entry {
    const p = documentPath(doc, tenant);
    const e = this.add(doc, p, 'studio', false, 'published', tenant);
    e.maker = actor;
    this.transaction(() => {
      this.write(this.contentBranch, `Publish ${e.key} (${doc.kind})\n\nBy ${actor} (${tenant}).`, [{ path: p, text: toYaml(doc), guard: 'create' }]);
      this.record({ tenant, actor, ...ev });
    });
    return e;
  }

  /** A state file the studio adds: never rewritten (R-11-23). */
  addStateFile(p: string, doc: any, message: string, ev: Omit<AuditEvent, 'at' | 'hash' | 'prevHash'>) {
    this.transaction(() => {
      this.write(this.contentBranch, message, [{ path: p, text: toYaml(doc), guard: 'create' }]);
      this.record(ev);
    });
  }

  /** One of the two state files a reviewed change replaces (users, settings; Issue I-44). It must still hold what the studio read. */
  replaceStateFile(p: string, doc: any, message: string, ev: Omit<AuditEvent, 'at' | 'hash' | 'prevHash'>) {
    const before = this.content?.files.get(p) ?? null;
    this.transaction(() => {
      this.write(this.contentBranch, message, [{ path: p, text: toYaml(doc), guard: 'replace', expect: before }]);
      this.record(ev);
    });
  }
}

/** Each file's records in the order of its chain; the files merged by time. */
function orderAudit(events: AuditEvent[]): AuditEvent[] {
  const streams = new Map<string, AuditEvent[]>();
  for (const e of events) {
    if (!e || typeof e !== 'object') continue;
    const s = streamOf(e);
    if (!streams.has(s)) streams.set(s, []);
    streams.get(s)!.push(e);
  }
  const ordered: AuditEvent[][] = [];
  for (const list of streams.values()) {
    list.sort((a, b) => String(a.at).localeCompare(String(b.at)));
    const next = new Map<string, AuditEvent[]>();
    for (const e of list) next.set(e.prevHash ?? GENESIS, [...(next.get(e.prevHash ?? GENESIS) ?? []), e]);
    const out: AuditEvent[] = [];
    const seen = new Set<AuditEvent>();
    let cur = GENESIS;
    for (;;) {
      const n = (next.get(cur) ?? []).find((x) => !seen.has(x));
      if (!n) break;
      out.push(n);
      seen.add(n);
      cur = n.hash ?? '';
    }
    for (const e of list) if (!seen.has(e)) out.push(e);
    ordered.push(out);
  }
  const all: AuditEvent[] = [];
  const idx = ordered.map(() => 0);
  for (;;) {
    let best = -1;
    for (let i = 0; i < ordered.length; i++) {
      if (idx[i] >= ordered[i].length) continue;
      if (best < 0 || String(ordered[i][idx[i]].at) < String(ordered[best][idx[best]].at)) best = i;
    }
    if (best < 0) break;
    all.push(ordered[best][idx[best]++]);
  }
  return all;
}

export function walkYaml(dir: string): string[] {
  const out: string[] = [];
  for (const ent of fs.readdirSync(dir, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name))) {
    const p = path.join(dir, ent.name);
    if (ent.isDirectory()) out.push(...walkYaml(p));
    else if (ent.name.endsWith('.yaml') || ent.name.endsWith('.yml')) out.push(p);
  }
  return out;
}

function leafDiff(a: any, b: any, prefix = '', out: Record<string, { before: any; after: any }> = {}) {
  const keys = new Set([...Object.keys(a ?? {}), ...Object.keys(b ?? {})]);
  for (const k of keys) {
    const p = prefix ? `${prefix}.${k}` : k;
    const x = a?.[k];
    const y = b?.[k];
    if (JSON.stringify(x) === JSON.stringify(y)) continue;
    if (x && y && typeof x === 'object' && typeof y === 'object' && !Array.isArray(x) && !Array.isArray(y)) leafDiff(x, y, p, out);
    else out[p] = { before: x, after: y };
  }
  return out;
}
