import { clone } from '../core/canonical.js';
import { compareReleases } from '../core/names.js';
import { SEED_HEADER } from '../core/store.js';
import { parseYamlAll, toYaml } from '../core/yaml.js';
import type { StudioEnv } from '../env.js';
import { zip } from '../export/zip.js';
import { FORMAT, type BundleFile } from './bundle.js';

// A training extraction bundle (I-33): the factory's WPS scheme, as an extraction would deliver it,
// under the scheme scope uae.wpsx so that it imports beside the factory's own WPS with nothing
// shared. Every document, script, sample and test is there, with an inventory that maps each file of
// the "source" (here, the factory's own files) to what it became, and findings. It is what the tests
// import, and what the Import page offers to try the import on. Its values are the factory's
// synthetic ones.

const FROM = 'uae.wps';

/** Rename the scheme throughout: names, message ids, extension paths and facts, test ids, samples. */
function rename(text: string, to: string): string {
  const last = to.split('.').pop()!;
  const cap = last[0].toUpperCase() + last.slice(1);
  return text
    .replace(/uae\.wps(?![a-z])/g, to)
    .replace(/\buae: \{ wps:/g, `uae: { ${last}:`)
    .replace(/\bWps(Batch|Item)\b/g, `${cap}$1`)
    .replace(/\bWPS-([A-Z]+-\d{3})\b/g, `${last.toUpperCase()}-$1`)
    .replace(/samples\/wps-/g, `samples/${last}-`);
}

const KIND_OF: Record<string, string> = { activity: 'activity', rule: 'rule', ruleset: 'rule', table: 'table', workflow: 'workflow', port: 'port', simulator: 'message', extension: 'message', scheme: 'message', test: 'test' };

export function wpsTrainingBundle(env: StudioEnv, to = 'uae.wpsx'): BundleFile[] {
  const last = to.split('.').pop()!;
  // The factory as the seed published it on the branch: each file's first line names its source (R-11-21).
  // Of a source published at more than one release, its latest; a major line a later major replaces is not taken (R-11-35).
  const seeded = new Map<string, string>();
  const at = new Map<string, string>();
  const current = new Set(env.store.current().map((e) => `${e.name}@${e.release}`));
  const major = (n: string) => /^(.*)\.v(\d+)$/.exec(n);
  const later = new Set(env.store.current().map((e) => major(e.name)).filter(Boolean).flatMap((m) => Array.from({ length: Number(m![2]) - 1 }, (_, i) => `${m![1]}.v${i + 1}`)));
  for (const [p, text] of [...(env.store.content?.files ?? [])].sort(([x], [y]) => x.localeCompare(y))) {
    const m = SEED_HEADER.exec(text);
    if (!m || !m[1].startsWith(`factory/${FROM}/`)) continue;
    const body = text.slice(text.indexOf('\n') + 1);
    const doc = parseYamlAll(body.replace(/^# Generated by .*\n/, '')).find((d: any) => d && typeof d === 'object');
    if (doc?.kind !== 'test' && doc?.kind !== 'pack' && doc?.release && !current.has(`${doc.kind === 'scheme' ? `scheme:${doc.scope}` : doc.name}@${doc.release}`)) continue;
    if (doc?.name && later.has(doc.name)) continue;
    const rel = doc?.release ?? (/@([\d.]+)\.yaml$/.exec(p)?.[1] ?? '0.0.0');
    if (at.has(m[1]) && compareReleases(rel, at.get(m[1])!) <= 0) continue;
    seeded.set(m[1], body);
    at.set(m[1], rel);
  }
  const files: BundleFile[] = [];
  const inventory: any[] = [];
  const sourceFiles: string[] = [];
  const excluded: { path: string; why: string }[] = [];
  let n = 0;
  const id = () => `SRC-${String(++n).padStart(4, '0')}`;

  for (const [rel, body] of [...seeded].sort(([a], [b]) => a.localeCompare(b))) {
    sourceFiles.push(rel);
    const text = rename(body.replace(/^# Generated by .*\n/, ''), to);
    const docs = parseYamlAll(text).filter(Boolean);
    const doc = docs[0];
    if (doc?.kind === 'pack') { excluded.push({ path: rel, why: 'The pack manifest is not content: the studio writes it when the pack is built' }); continue; }
    // The scheme's planned messages are not built: the extraction retires them, with the reason, so
    // that the scheme can be published (R-05-22); building them is a later release.
    if (doc?.kind === 'scheme') {
      for (const msg of (doc.messages ?? []).filter((x: any) => x.disposition?.planned)) {
        inventory.push({ id: id(), source: { path: rel, symbol: msg.id, kind: 'message' }, summary: msg.title ?? msg.id, target: { kind: 'retire' }, note: `Planned in the source, not built: ${msg.disposition.planned}. Retired from this release; a later release builds it.`, confidence: 'high' });
      }
      doc.messages = (doc.messages ?? []).filter((x: any) => !x.disposition?.planned);
    }
    const dir = doc?.kind === 'test' ? 'tests' : 'artefacts';
    const out = `${dir}/${rel.slice(`factory/${FROM}/`.length).replace(/uae\.wps(?![a-z])/g, to).replace(/WPS-/g, `${last.toUpperCase()}-`)}`;
    if (doc?.implementation?.script) doc.implementation.script = doc.implementation.script.replace(/@[\d.]+(\.(ts|js|py))$/, '$1');
    files.push({ name: out, content: toYaml(doc) });
    inventory.push({
      id: id(), source: { path: rel, symbol: doc?.name ?? doc?.id ?? doc?.scope, kind: KIND_OF[doc?.kind] ?? 'other' },
      summary: doc?.title ?? doc?.kind,
      target: doc?.kind === 'test' ? { kind: 'test', name: doc.id } : { kind: 'artefact', name: doc?.kind === 'scheme' ? `scheme:${doc.scope}` : doc?.name },
      ...(doc?.name?.startsWith('uae.p.') || doc?.name?.startsWith('p.') ? { reuse: 'as-is' } : {}),
      confidence: 'high',
    });
  }
  // Scripts-behind, translated from the source's code.
  // The factory's scripts and samples are read from the branch, where the seed published them (R-11-25).
  // A script re-released with its activity (`<name>@<release>`) is the one its latest release runs; the bundle names it plainly.
  // A script first published with a later release (`uae.wps.map.rri-in.v1@1.1.0`, I-133) has no plain file: it is named plainly too.
  const plain = [...new Set(env.scripts.list().filter((x) => x.startsWith(`${FROM}.`)).map((x) => x.replace(/@[\d.]+(\.(ts|js|py))$/, '$1')))];
  for (const f of plain.sort()) {
    const stem = f.replace(/\.(ts|js|py)$/, '');
    const rel = `studio/scripts/${env.scripts.list().includes(f) ? f : env.scripts.list().filter((x) => x.replace(/@[\d.]+(\.(ts|js|py))$/, '$1') === f).sort().pop()}`;
    sourceFiles.push(rel);
    const name = rename(f, to);
    files.push({ name: `scripts/${name}`, content: rename(env.scripts.find(stem, env.store.get(stem)?.release)!.source, to) });
    inventory.push({ id: id(), source: { path: rel, kind: 'script', symbol: 'run' }, summary: 'Code of the activity, translated into its script-behind', target: { kind: 'artefact', name: name.replace(/\.(ts|py)$/, '') }, confidence: 'high' });
  }
  // Synthetic samples.
  for (const f of [...env.store.factorySamples].filter((x) => x.startsWith('wps-')).sort()) {
    const rel = `studio/fixtures/samples/${f}`;
    sourceFiles.push(rel);
    const name = f.replace(/^wps-/, `${last}-`);
    files.push({ name: `samples/${name}`, content: rename(env.store.sampleFiles.get(f)!, to) });
    inventory.push({ id: id(), source: { path: rel, kind: 'sample' }, summary: 'A synthetic sample file', target: { kind: 'sample', name }, confidence: 'high' });
  }
  // The bank's configuration: its values for the scheme's parameters are per artefact, so the
  // extracted scheme needs its own. Here, the example bank's routing code for the renamed rule.
  const cfgRel = 'examples/bank/configuration-set.yaml';
  sourceFiles.push(cfgRel);
  const cfg = clone(env.store.all().filter((e) => e.kind === 'configuration-set' && e.source === 'spec' && e.path === cfgRel)
    .sort((a, b) => compareReleases(a.doc.release ?? '0.0.0', b.doc.release ?? '0.0.0')).pop()?.doc);
  const next = JSON.parse(JSON.stringify(cfg));
  // The next minor of the example bank's configuration set: the bundle's release is a new one, never one already published.
  const [M, m] = String(cfg.release ?? '1.0.0').split('.').map(Number);
  next.release = `${M}.${m + 1}.0`;
  next.title = `${cfg.title}, with the values of ${to}`;
  next.accepts = [...(next.accepts ?? []), { scope: to, release: '1.0.0' }];
  for (const v of cfg.values ?? []) {
    if (String(v.parameter).startsWith(`${FROM}.`)) next.values.push({ ...v, parameter: rename(v.parameter, to) });
  }
  files.push({ name: `configuration/${cfg.tenant}.yaml`, content: toYaml(next) });
  inventory.push({ id: id(), source: { path: cfgRel, kind: 'config', symbol: 'values' }, summary: `The bank's values for the ${FROM} parameters, carried to ${to}`, target: { kind: 'configuration', name: `${cfg.tenant}@${next.release}` }, confidence: 'high' });

  const manifest = {
    kind: 'extraction', format: FORMAT, scope: to,
    title: `WPS, extracted as ${to} (training bundle)`,
    source: {
      system: 'WPS salary files (training copy of the factory scheme)', repository: 'bfs-payment-hub-authoring', revision: 'factory', engine: 'studio documents',
      languages: ['yaml', 'typescript'], files: sourceFiles, excluded,
    },
    extractedBy: { tool: 'studio training generator', model: 'none', date: '2026-11-19', promptRef: 'docs/import/EXTRACTION-PROMPT.md' },
    dataPolicy: 'synthetic',
  };
  const findings = [
    { kind: 'question', text: 'The WPS content is provisional: it was written from public sources, not the CBUAE rulebook. Confirm each rule with the scheme expert before publishing.', source: `factory/${FROM}/scheme.yaml` },
    { kind: 'decision', text: 'Three messages of the dispatch table are planned, not built (a disbursement correction and refunds). They are retired from this release, each with its reason in the inventory, so that the scheme can be published; a later release builds them.', source: `factory/${FROM}/scheme.yaml` },
    { kind: 'error-scenario', text: 'The salary file submission is a composite: send, wait one business day for the acknowledgement, read it. No acknowledgement ends as pending; a status inquiry follows, never a resend.', source: `factory/${FROM}/workflows/${FROM}.sub.submit-salary-file.v1.yaml` },
  ];
  files.push({ name: 'extraction.yaml', content: toYaml(manifest) });
  files.push({ name: 'inventory.yaml', content: toYaml({ items: inventory }) });
  files.push({ name: 'findings.yaml', content: toYaml({ findings }) });
  files.push({ name: 'README.md', content: `# ${manifest.title}\n\nAn extraction bundle in the format of docs/import/EXTRACTION-PROMPT.md. Import it from the studio's Import page, or: npm run studio -- import <this zip>.\n` });
  return files;
}

export function bundleZip(files: BundleFile[]): Buffer {
  return zip(files.map((f) => ({ name: f.name, content: Buffer.from(f.content, 'utf8') })));
}
