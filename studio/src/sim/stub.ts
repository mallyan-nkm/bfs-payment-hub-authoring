// A deployable stub of a simulator (R-07-11, C10-S5): one plain Node.js file with no dependency,
// holding the simulator definition and the same scenario semantics as the studio runtime, served
// over HTTP. It belongs in a test pack and never in a promotable pack.
//
//   node stub.js --port 7071 --scenario accept [--time-scale 0.001]
//   POST /message {"id","type","correlation":{...},"expectsReply":true}   -> the reply on the connection
//   GET  /deliveries                                                       -> later replies, as they fall due
//   POST /scenario {"scenario":"reject"}                                   -> switch scenario, reset state

export function stubSource(sim: any): string {
  return `#!/usr/bin/env node
// Generated by the TransactHub Designer Studio from ${sim.name}@${sim.release}. Do not edit; regenerate.
// A deployable stub for pre-production. Functional only: no load, back-pressure or soak behaviour.
'use strict';
const http = require('http');
const SIM = ${JSON.stringify(sim)};
const args = process.argv.slice(2);
const arg = (k, d) => { const i = args.indexOf('--' + k); return i >= 0 ? args[i + 1] : d; };
const PORT = Number(arg('port', 7071));
const SCALE = Number(arg('time-scale', 1));
let scenario = arg('scenario', 'accept');
let cursor = 0, seq = 0, conv = new Map(), due = [];
function durMs(s) { const m = /^P(?:(\\d+)D)?(?:T(?:(\\d+)H)?(?:(\\d+)M)?(?:(\\d+(?:\\.\\d+)?)S)?)?$/.exec(s || ''); if (!m) return 0; return ((((+(m[1]||0))*24 + +(m[2]||0))*60 + +(m[3]||0))*60 + +(m[4]||0))*1000; }
function steps() { const sc = SIM.scenarios.find((x) => x.name === scenario); if (!sc) throw new Error('No scenario ' + scenario); return sc; }
function emit(st, req, sync) {
  const sc = steps();
  const msg = { id: 'stub-' + (++seq), type: st.send, status: st.status, reasonCode: st.reasonCode, correlation: req ? req.correlation || {} : {}, inReplyTo: req && req.id, malformed: !!sc.malformed };
  if (sync) return msg;
  const at = Date.now() + durMs(st.after) * SCALE;
  due.push({ at, message: msg });
  if (st.duplicate) due.push({ at, message: Object.assign({}, msg, { copy: 1 }) });
  return msg;
}
function play(list, req, sync) {
  let reply, noReply = false;
  for (const st of list) {
    if (st.noReply) { noReply = true; continue; }
    if (!st.send) continue;
    const now = sync && !reply && !st.after && !noReply;
    const m = emit(st, req, now);
    if (now) reply = m;
  }
  if (reply) return { kind: 'reply', message: reply };
  return sync ? { kind: 'no-reply' } : { kind: 'ack' };
}
function receive(m) {
  const sc = steps(); const s = sc.steps; const sync = m.expectsReply !== false;
  const c = conv.get(m.id);
  if (c) { if (c.fails > 0) { c.fails--; return { kind: 'transient' }; } if (c.pending) { c.res = play(c.pending, m, sync); c.pending = null; } return c.res; }
  const st = s[cursor];
  if (!st || !st.expect || (m.type && st.expect !== m.type)) return sync ? { kind: 'no-reply' } : { kind: 'ack' };
  cursor++;
  const rest = []; while (cursor < s.length && !s[cursor].expect) rest.push(s[cursor++]);
  if (st.failTimes > 0) { conv.set(m.id, { fails: st.failTimes - 1, pending: rest }); return { kind: 'transient' }; }
  const res = play(rest, m, sync); conv.set(m.id, { fails: 0, res }); return res;
}
http.createServer((req, res) => {
  const chunks = []; req.on('data', (d) => chunks.push(d)); req.on('end', () => {
    const body = Buffer.concat(chunks).toString('utf8'); // decoded once: a character split between chunks stays whole
    const send = (code, o) => { res.writeHead(code, { 'content-type': 'application/json' }); res.end(JSON.stringify(o)); };
    try {
      if (req.method === 'POST' && req.url === '/message') {
        const r = receive(JSON.parse(body || '{}'));
        if (r.kind === 'transient') return send(503, { error: 'TransientError' });
        if (r.kind === 'no-reply') return; // never answers; the caller's timeout ends the attempt
        return send(200, r);
      }
      if (req.method === 'GET' && req.url === '/deliveries') { const now = Date.now(); const ready = due.filter((d) => d.at <= now); due = due.filter((d) => d.at > now); return send(200, ready.map((d) => d.message)); }
      if (req.method === 'POST' && req.url === '/scenario') { scenario = JSON.parse(body).scenario; cursor = 0; conv = new Map(); due = []; steps(); return send(200, { scenario }); }
      if (req.method === 'GET' && req.url === '/') return send(200, { simulator: SIM.name, release: SIM.release, port: SIM.port, scenario, scenarios: SIM.scenarios.map((x) => x.name) });
      send(404, { error: 'not found' });
    } catch (e) { send(400, { error: String(e.message || e) }); }
  });
}).listen(PORT, () => console.log(SIM.name + ' stub on port ' + PORT + ', scenario ' + scenario));
`;
}
