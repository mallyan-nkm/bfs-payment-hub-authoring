#!/usr/bin/env python3
"""Generate the runtime's Prometheus alert and recording rules from the agreed targets (R-09-72).

Reads targets.yaml beside this file and writes ../alerts/transacthub.rules.yaml, a Prometheus rule file that Prometheus
loads (rule_files) and that an OpenTelemetry collector's Prometheus-compatible back end (Mimir, Thanos, Cortex) loads too.
The metric names are the hosts' OpenTelemetry instruments as Prometheus names them: dots to underscores, a counter gains
_total, a unit of seconds gains _seconds, a unit in braces adds nothing.

Run: python3 runtime/observability/slo/build_rules.py          # write the rules
     python3 runtime/observability/slo/build_rules.py --check  # exit 1 when the rules file is not current
"""
import pathlib
import re
import sys

import yaml

HERE = pathlib.Path(__file__).resolve().parent
OUT = HERE.parent / "alerts" / "transacthub.rules.yaml"
HEADER = "# Generated by runtime/observability/slo/build_rules.py from targets.yaml. Edit the targets, then run it again.\n"


def seconds(iso):
    m = re.fullmatch(r"P(?:(\d+)D)?(?:T(?:(\d+)H)?(?:(\d+)M)?(?:(\d+)S)?)?", iso)
    if not m:
        raise ValueError("not an ISO 8601 duration: %s" % iso)
    d, h, mi, s = (int(x or 0) for x in m.groups())
    return d * 86400 + h * 3600 + mi * 60 + s


def rules(t):
    tp = t["throughput"]
    rec = [
        {"record": "th:payment_lines:rate5m", "expr": "sum(rate(th_payment_lines_total[%s]))" % tp["window"]},
        {"record": "th:payments_open:by_distribution", "expr": "max by (th_distribution) (th_payments_open)"},
    ]
    alerts = [{
        "alert": "TransactHubLineThroughputBelowTarget",
        # Busy but slow: attempts are waiting on the workers' queues while lines end slower than the target.
        "expr": "sum(rate(th_payment_lines_total[%s])) < %d and sum(th_queue_in_flight) > 0" % (tp["window"], tp["linesPerSecond"]),
        "for": tp["for"],
        "labels": {"severity": "warning", "slo": "throughput"},
        "annotations": {
            "summary": "Lines end slower than %d a second while attempts wait on the queues" % tp["linesPerSecond"],
            "description": "The agreed target is %d lines a second sustained, each runtime node at %d or more cores (%s). Check the workers' "
                           "queues, the engine's and the store's dashboards, and the nodes' cores." % (tp["linesPerSecond"], tp["cores"], tp["agreed"]),
            "runbook": "#/service/errors/TransientError",
        },
    }]
    for a in t["ackWait"]:
        wait = seconds(a["wait"])
        sel = 'th_await_oldest_seconds{th_scheme="%s",th_message="%s"}' % (a["scheme"], a["message"])
        for sev, limit, name in (("warning", int(wait * a["warnAt"]), "Due"), ("critical", wait, "Overdue")):
            alerts.append({
                "alert": "TransactHubAck%s" % name,
                "expr": "max by (th_tenant, th_scheme, th_message) (%s) > %d" % (sel, limit),
                "for": "5m",
                "labels": {"severity": sev, "slo": "ack-wait", "scheme": a["scheme"]},
                "annotations": {
                    "summary": "A %s file has waited %s for its acknowledgement" % (a["message"], "more than %d%% of its wait" % round(a["warnAt"] * 100) if name == "Due" else "past its wait"),
                    "description": "The wait is the bank's value of %s, by default %s (%s); the payment goes pending when it passes." % (a["parameter"], a["wait"], a["agreed"]),
                    "runbook": "#/service/errors/Timeout",
                },
            })
    h = t["holdExpiry"]
    exp = seconds(h["expiry"])
    alerts.append({
        "alert": "TransactHubHoldDue",
        "expr": "max by (th_tenant, th_hold_kind) (th_holds_oldest_seconds) > %d" % int(exp * h["warnAt"]),
        "for": "5m",
        "labels": {"severity": "warning", "slo": "hold-expiry"},
        "annotations": {
            "summary": "A hold has waited more than %d%% of its expiry for a decision" % round(h["warnAt"] * 100),
            "description": "The expiry is %s, by default %s (%s). Decide the hold in the operations console before it expires." % (h["parameter"], h["expiry"], h["agreed"]),
            "runbook": "#/service/errors/ops.HoldClosed",
        },
    })
    alerts.append({
        "alert": "TransactHubHoldExpired",
        "expr": "sum by (th_tenant) (increase(th_holds_expired_total[1h])) > 0",
        "labels": {"severity": "critical", "slo": "hold-expiry"},
        "annotations": {
            "summary": "A hold reached its expiry with no decision",
            "description": "A hold is decided before its expiry (%s). The payment took its expired path." % h["agreed"],
            "runbook": "#/service/errors/ops.HoldClosed",
        },
    })
    o = t["openPayments"]
    if o.get("maxPerDistribution") is not None:
        alerts.append({
            "alert": "TransactHubOpenPaymentsAboveTarget",
            "expr": "max by (th_distribution) (th_payments_open) > %d" % o["maxPerDistribution"],
            "for": o["for"],
            "labels": {"severity": "warning", "slo": "open-payments"},
            "annotations": {"summary": "A distribution has more open payments than its target", "description": "Agreed in %s." % o["agreed"], "runbook": "#/service/errors/service.RemovalRefused"},
        })
    return {"groups": [
        {"name": "transacthub-slo-recording", "interval": "30s", "rules": rec},
        {"name": "transacthub-slo-alerts", "interval": "30s", "rules": alerts},
    ]}


def text():
    t = yaml.safe_load((HERE / "targets.yaml").read_text())
    return HEADER + yaml.safe_dump(rules(t), sort_keys=False, width=140)


if __name__ == "__main__":
    out = text()
    if "--check" in sys.argv:
        current = OUT.read_text() if OUT.exists() else ""
        if current != out:
            print("%s is not current: run python3 runtime/observability/slo/build_rules.py" % OUT)
            sys.exit(1)
        print("%s is current" % OUT.relative_to(HERE.parent.parent.parent))
        sys.exit(0)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(out)
    print("written %s" % OUT.relative_to(HERE.parent.parent.parent))
