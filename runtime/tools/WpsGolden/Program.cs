using TransactHub.WpsGolden;

// Writes the golden corpus: every case of Corpus.Run evaluated by the source's own rule classes.
var outFile = args.Length > 0 ? args[0] : "golden.json";
var cases = Corpus.Run();
var doc = new System.Text.Json.Nodes.JsonObject
{
    ["note"] = "Generated by runtime/tools/WpsGolden from the TransactHub source's WPS rule classes. Synthetic inputs. Do not edit: regenerate.",
    ["count"] = cases.Count,
    ["cases"] = cases,
};
File.WriteAllText(outFile, doc.ToJsonString(new System.Text.Json.JsonSerializerOptions { WriteIndented = true, Encoder = System.Text.Encodings.Web.JavaScriptEncoder.UnsafeRelaxedJsonEscaping }) + "\n");
Console.WriteLine($"{cases.Count} cases written to {outFile}");
